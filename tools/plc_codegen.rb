# frozen_string_literal: true

# PLC コードジェネレータ
# 解析済み IREP から KV スクリプト用のメモリ初期化コードを生成します。

require_relative "mrb_parser"
require_relative "memory_map"
require "plc_access"

module MrubycOnPlc
  class PlcCodegen
    include MemoryMap

    def initialize(irep, steps_per_cycle: 50)
      @irep = irep
      @steps_per_cycle = steps_per_cycle
    end

    # EM レジスタ初期化用の KV スクリプトを生成
    def generate
      lines = []
      lines << "' ======================================="
      lines << "' mruby/c VM - Memory Initialization"
      lines << "' Generated by mruby/c on PLC plc_codegen.rb"
      lines << "' ======================================="
      lines << ""

      lines.concat(generate_vm_state)
      lines << ""
      lines.concat(generate_bytecode)
      lines << ""
      lines.concat(generate_pool)
      lines << ""
      lines.concat(generate_device_table)

      lines.join("\n")
    end

    # メモリイメージを Hash として返す (シミュレータ用)
    # { address => value, ... }
    def memory_image
      image = {}

      # VM 状態
      image[PC_ADDR] = 0
      image[STATUS_ADDR] = VM_RUNNING
      image[ERROR_ADDR] = 0
      image[STEP_COUNT_ADDR] = 0
      image[STEP_COUNT_ADDR + 1] = 0
      image[STEPS_PER_CYCLE] = @steps_per_cycle
      image[BYTECODE_LEN_ADDR] = @irep.ilen
      image[NREGS_ADDR] = @irep.nregs
      image[NLOCALS_ADDR] = @irep.nlocals

      # バイトコード
      @irep.instructions.each_byte.each_with_index do |b, i|
        image[BYTECODE_BASE + i] = b
      end

      # 定数プール
      @irep.pool.each_with_index do |entry, i|
        addr = POOL_BASE + i * 2
        case entry.type
        when :int32
          lo = entry.value & 0xFFFF
          hi = (entry.value >> 16) & 0xFFFF
          image[addr] = lo
          image[addr + 1] = hi
        when :int64
          # 下位32ビットのみ使用
          val = entry.value & 0xFFFFFFFF
          lo = val & 0xFFFF
          hi = (val >> 16) & 0xFFFF
          image[addr] = lo
          image[addr + 1] = hi
        end
      end

      # レジスタファイル初期化 (全て0)
      @irep.nregs.times do |i|
        addr = REG_FILE_BASE + i * 2
        image[addr] = 0
        image[addr + 1] = 0
      end

      # デバイスマッピングテーブル
      image[NUM_SYMBOLS_ADDR] = @irep.symbols.size
      general_global_next = GENERAL_GLOBAL_BASE
      @irep.symbols.each_with_index do |sym, idx|
        table_addr = DEVICE_TABLE_BASE + idx * DEVICE_TABLE_STRIDE
        parsed = parse_device_symbol(sym)
        if parsed
          image[table_addr] = parsed[:device_type]
          image[table_addr + 1] = parsed[:z_offset]
        else
          image[table_addr] = DEVICE_TYPE_EM
          image[table_addr + 1] = general_global_next
          general_global_next += 2
        end
      end

      image
    end

    private

    def generate_vm_state
      lines = []
      lines << "' --- VM State ---"
      lines << "#{MemoryMap.device(PC_ADDR)} = 0           ' PC = 0"
      lines << "#{MemoryMap.device(STATUS_ADDR)} = #{VM_RUNNING}           ' STATUS = running"
      lines << "#{MemoryMap.device(ERROR_ADDR)} = 0           ' ERROR = none"
      lines << "#{MemoryMap.device_long(STEP_COUNT_ADDR)} = 0     ' STEP_COUNT = 0"
      lines << "#{MemoryMap.device(STEPS_PER_CYCLE)} = #{@steps_per_cycle}          ' STEPS_PER_CYCLE"
      lines << "#{MemoryMap.device(BYTECODE_LEN_ADDR)} = #{@irep.ilen}         ' BYTECODE_LEN"
      lines << "#{MemoryMap.device(NREGS_ADDR)} = #{@irep.nregs}          ' NREGS"
      lines << "#{MemoryMap.device(NLOCALS_ADDR)} = #{@irep.nlocals}          ' NLOCALS"
      lines << "#{MemoryMap.device(RESET_REQ_ADDR)} = 0          ' RESET_REQ = off"
      lines << ""
      lines << "' --- Clear Register File ---"
      lines << "FOR Z1 = #{REG_FILE_BASE} TO #{REG_FILE_BASE + @irep.nregs * 2 - 1}"
      lines << "    EM0:Z1 = 0"
      lines << "NEXT"
      lines
    end

    def generate_bytecode
      lines = []
      lines << "' --- Bytecode (#{@irep.ilen} bytes) ---"

      @irep.instructions.each_byte.each_with_index do |b, i|
        lines << "#{MemoryMap.device(BYTECODE_BASE + i)} = #{b}"
      end

      lines
    end

    def generate_pool
      return [] if @irep.pool.empty?

      lines = []
      lines << "' --- Constant Pool (#{@irep.pool.size} entries) ---"

      @irep.pool.each_with_index do |entry, i|
        addr = POOL_BASE + i * 2
        case entry.type
        when :int32, :int64
          lines << "#{MemoryMap.device_long(addr)} = #{entry.value}    ' Pool[#{i}]"
        when :float
          lines << "' Pool[#{i}] = #{entry.value} (float - not supported in milestone 1)"
        else
          lines << "' Pool[#{i}] = #{entry} (type #{entry.type} - not supported)"
        end
      end

      lines
    end

    def generate_device_table
      return [] if @irep.symbols.empty?

      lines = []
      lines << "' --- Device Mapping Table (#{@irep.symbols.size} symbols) ---"
      lines << "#{MemoryMap.device(NUM_SYMBOLS_ADDR)} = #{@irep.symbols.size}    ' NUM_SYMBOLS"

      general_global_next = GENERAL_GLOBAL_BASE
      @irep.symbols.each_with_index do |sym, idx|
        table_addr = DEVICE_TABLE_BASE + idx * DEVICE_TABLE_STRIDE
        parsed = parse_device_symbol(sym)
        if parsed
          lines << "#{MemoryMap.device(table_addr)} = #{parsed[:device_type]}    ' #{sym} type=#{DEVICE_TYPE_NAMES[parsed[:device_type]]}"
          lines << "#{MemoryMap.device(table_addr + 1)} = #{parsed[:z_offset]}    ' #{sym} Z offset"
        else
          lines << "#{MemoryMap.device(table_addr)} = #{DEVICE_TYPE_EM}    ' #{sym} type=EM (auto)"
          lines << "#{MemoryMap.device(table_addr + 1)} = #{general_global_next}    ' #{sym} -> EM#{general_global_next}"
          general_global_next += 2
        end
      end

      lines
    end

    # デバイスパターン (MR を R より先にマッチさせる)
    # CR はインデックス扱い不可のため非対応
    # B は16進アドレス (例: $B1F), 他は10進
    DEVICE_PATTERN = /^\$(EM|DM|ZF|MR|R|B|L|T|C)([0-9A-Fa-f]+)$/i
    # dev コマンド用: $ なしパターン
    DEVICE_PATTERN_BARE = /^(EM|DM|ZF|MR|R|B|L|T|C)([0-9A-Fa-f]+)$/i
    DEVICE_NAME_TO_TYPE = {
      "EM" => DEVICE_TYPE_EM, "DM" => DEVICE_TYPE_DM, "ZF" => DEVICE_TYPE_ZF,
      "R" => DEVICE_TYPE_R, "MR" => DEVICE_TYPE_MR, "B" => DEVICE_TYPE_B,
      "L" => DEVICE_TYPE_L, "T" => DEVICE_TYPE_T, "C" => DEVICE_TYPE_C,
    }.freeze
    DEVICE_TYPE_NAMES = DEVICE_NAME_TO_TYPE.invert.freeze

    # KvDevice を使ってデバイスアドレスの Z レジスタ用オフセットを取得
    # HEXDEC (R, MR 等): MR200 → 32, R100 → 16
    # HEX (B): B10 → 16
    # DEC (EM, DM 等): そのまま
    def self.device_z_offset(device_name, addr_str)
      PlcAccess::Protocol::Keyence::KvDevice.new("#{device_name}#{addr_str}").number
    end

    def parse_device_symbol(sym)
      self.class.parse_device_symbol(sym)
    end

    # シンボル名 ($DM100) からデバイス情報をパース
    # address: 元のアドレス (PLC アダプタ通信用)
    # z_offset: Z レジスタ用オフセット (マッピングテーブル・シミュレータ用)
    def self.parse_device_symbol(sym)
      return nil unless sym
      m = sym.match(DEVICE_PATTERN)
      return nil unless m
      device_name = m[1].upcase
      addr_str = m[2]
      z_offset = device_z_offset(device_name, addr_str)
      { device_type: DEVICE_NAME_TO_TYPE[device_name], address: addr_str,
        z_offset: z_offset, device_name: device_name }
    end

    # デバイス名 (DM100, $ なし) からデバイス情報をパース
    def self.parse_device_name(name)
      return nil unless name
      m = name.match(DEVICE_PATTERN_BARE)
      return nil unless m
      device_name = m[1].upcase
      addr_str = m[2]
      z_offset = device_z_offset(device_name, addr_str)
      { device_type: DEVICE_NAME_TO_TYPE[device_name], address: addr_str,
        z_offset: z_offset, device_name: device_name }
    end
  end
end

# コマンドラインから実行した場合
if __FILE__ == $0
  require_relative "mrb_parser"

  if ARGV.empty?
    puts "Usage: ruby plc_codegen.rb <file.mrb>"
    exit 1
  end

  data = File.binread(ARGV[0])
  parser = MrubycOnPlc::MrbParser.new(data).parse
  codegen = MrubycOnPlc::PlcCodegen.new(parser.irep)
  puts codegen.generate
end
