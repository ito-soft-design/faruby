# 添字への複合代入 (x[i] op= v)
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# **ラダーの `DM0.0` に当たるものです。** インデックス修飾ではビットを指定
# できないので、読んで直して書きます。
#
#   $D[a] |= 1 << 3     ビットを立てる
#   $D[a] &= ~(1 << 3)  落とす
#   $D[a][3]            読む
#
# `x[i] op= v` は `[]` と `[]=` のメソッド呼び出しになります。素の `x[i]` が
# OP_GETIDX なのに複合代入だけ呼び出しになるのは mruby の出し方で、
# ホスト側で専用命令に置き換えています。配列とハッシュにも同じ穴が空いて
# いたので、まとめて塞がりました。
#
# 期待値:
#   $D150 = 9       $D[i] = 1 にビット 3 を立てる
#   $D151 = 14      $D[i] = 15 からビット 0 を落とす
#   $D152 = 1       立てたビットを添字で読む
#   $D153 = 15      配列の要素を足す (a[0] += 5)
#   $D154 = 3       ハッシュの値を足す (h["n"] += 2)
#   $D155 = 22      引数 2 個の [] は連続読みのまま
#
# 実機でのみ意味を持つ検証。

i = 150
$D[i] = 1
$D[i] |= 1 << 3

$D151 = 15
j = 151
$D[j] &= ~(1 << 0)

$D152 = 0
$D152 = 1 if $D[i][3] == 1

a = [10, 20]
a[0] += 5
$D153 = a[0]

h = { "n" => 1 }
h["n"] += 2
$D154 = h["n"]

$D160 = 11
$D161 = 22
b = $D[160, 2]
$D155 = b[1]
