# 文字列のリテラルとデバイスへの書き込み
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# 実体は配列プールのスロット。見出しの後ろに 1 ワード 2 バイトで詰め、
# **先の文字が上位バイト**。KV-5000 の文字列デバイスと同じ並びなので、
# デバイスへの書き込みはワード単位の写しで済む。
#
# バイト列は変換しない。ソースの文字コードがそのままデバイスへ出る。
#
# 書き方は 2 つ。
#   $D880   = "abc"    終端付き。バイト列 + 0
#   $D887T6 = "abc"    固定長。余りは FARUBY_STR_FILL、はみ出す分は切り詰め
#
# 期待値 (16ビット符号なしで読む):
#   $D880U = 24930   "ab"      終端付き
#   $D881U = 25344   "c\0"
#   $D883U = 24930   "ab"      偶数バイトは終端に 1 ワード余分に要る
#   $D884U = 25444   "cd"
#   $D885U = 0       終端
#   $D887U = 24930   "ab"      固定長。足りない桁は 0x20 で埋める
#   $D888U = 25376   "c "
#   $D889U = 8224    "  "
#   $D891U = 16706   "AB"      ちょうど。終端は書かない
#   $D892U = 17220   "CD"
#   $D893U = 17734   "EF"
#   $D894U = 1234    次の桁にはみ出していない (書く前に置いた印)
#   $D895U = 24930   "ab"      はみ出す分は切り詰める
#   $D896U = 25444   "cd"
#   $D897U = 1234    切り詰めた先を触っていない (書く前に置いた印)
#   $D898U = 24930   "ab"      桁数が奇数
#   $D899U = 8224    "  "
#   $D900U = 8192    " \0"     最後のワードの下位バイトは桁の外なので 0
#   $D902U = 0       空文字列は終端だけ
#   $D904U = 58241   UTF-8 の "あ" 1 バイト目と 2 バイト目
#   $D905U = 33280   3 バイト目と終端
#   $D907U = 26729   "hi"      変数に入れた文字列
#   $D908U = 0       終端
#   $D909U = 26729   "hi"      同じ文字列を固定長でも書ける
#   $D910U = 8224    "  "
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルはプールを 1 スロット使う。16 スロットしかないので、
# 行を増やすときは残りに気をつけること。

FARUBY_STR_FILL = 0x20

$D880 = "abc"
$D883 = "abcd"
$D887T6 = "abc"

# ちょうど収まる桁。終端を書くと次の桁にはみ出す
$D894 = 1234
$D891T6 = "ABCDEF"

# 桁からはみ出す文字列は切り詰める。止めない
$D897 = 1234
$D895T4 = "abcdefgh"

$D898T5 = "ab"

$D902 = 1234
$D902 = ""

# バイト列は変換しない。UTF-8 のソースなら UTF-8 が出る
$D904 = "あ"

s = "hi"
$D907 = s
$D909T4 = s
