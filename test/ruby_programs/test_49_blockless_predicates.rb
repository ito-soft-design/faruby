# ブロック無しの any? / all? / none?
#
# 対象機種: KV-5000, KV-X500
#
# **`a.all?` は `a.all? { |x| x }` と同じです。** 中身をそのまま返す
# ブロック (恒等ブロック) を渡したものとして反復に入れるので、反復も
# フレームも判定もブロック付きと同じ道を通ります。
#
# **実機で効くのは irep の引き方です。** 恒等ブロックは `OP_RETURN R[1]`
# の 2 バイトで、**最後の irep** に足してあります。VM は
# `num_ireps - 1` で引くので、間違えると無い irep に飛びます。
# **使っているときだけ足します** (irep の上限は 16)。
#
# **test_47 と分けてあるのはこのためです。** あちらはブロックが多く、
# 恒等ブロックの 1 枠を足すと 18 になって上限を超えました。
#
# **ハッシュだけは反復しません。** Ruby はブロック無しのとき `[鍵, 値]` の
# 配列を見るので、中身がどうであれ常に真です。鍵をそのまま渡すと
# `{1 => nil}.all?` が偽になってしまいます。
#
# 期待値:
#   $DM1220 = 1        all? は全部真なら真
#   $DM1221 = 0        all? は nil が混ざれば偽
#   $DM1222 = 1        any? は真が 1 つあれば真
#   $DM1223 = 0        any? は全部偽なら偽 (false も偽)
#   $DM1224 = 1        none? は真が無ければ真
#   $DM1225 = 0        none? は真があれば偽
#   $DM1226 = 1        0 は真 (Ruby と同じ。整数の中身で見ていない)
#   $DM1227 = 1        空は all? と none? が真、any? が偽
#   $DM1228 = 1        ハッシュは中身によらず all? と any? が真
#   $DM1229 = 1        空のハッシュは any? が偽、none? が真
#   $DM1230 = 1        ブロック付きと併存する
#
# 実機でのみ意味を持つ検証。

a = [1, 2, 3]
$DM1220 = a.all? ? 1 : 0

b = [1, nil, 2]
$DM1221 = b.all? ? 1 : 0
$DM1222 = b.any? ? 1 : 0

c = [nil, false]
$DM1223 = c.any? ? 1 : 0
$DM1224 = c.none? ? 1 : 0

d = [nil, 1]
$DM1225 = d.none? ? 1 : 0

# 0 も真。整数の中身で判定していないこと
e = [0]
$DM1226 = e.any? ? 1 : 0

# 空は 1 回も回らないので、フレームを積まずに答えが決まる
empty = []
$DM1227 = (empty.all? && empty.none? && !empty.any?) ? 1 : 0

# ハッシュは [鍵, 値] の配列を見るので、値が nil でも真
h = { 1 => nil }
$DM1228 = (h.all? && h.any? && !h.none?) ? 1 : 0

g = {}
$DM1229 = (!g.any? && g.none? && g.all?) ? 1 : 0

# ブロック付きが壊れていないこと
$DM1230 = (b.any? && b.any? { |x| x == 2 }) ? 1 : 0
