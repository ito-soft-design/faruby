# ワードデバイスのアクセス幅サフィックス
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
# 期待値:
#   $D300  = -100    (16bit符号付き、DM300 の1ワードのみ)
#   $D310L = 100000  (32bit符号付き、DM310/DM311 の2ワード)
#   $D320U = 60000   (16bit符号なし、DM320 の1ワードのみ)
#   $total  = 99900
$D300 = -100
$D310L = 100000
$D320U = 60000
$M10 = 1
$total = $D310L + $D300
