# 実数の確認
#
# 期待値:
#   $DM520F = 3.0      実数の加算 2.5 + 0.5
#   $DM522F = 3.5      実数の除算 7.0 / 2.0 (切り下げない)
#   $DM524F = 5.5      整数と実数の混在 2.5 + 3
#   $DM526  = 3        実数をワードデバイスへ書くと0方向へ切り捨て
#   $DM528F = 2.0      整数をFデバイスへ書くと実数に変換される
#   $DM530  = 1        1 == 1.0 は真
#   $DM532  = 1        整数どうしの除算は切り下げのまま (7 / 2 = 3)
#
# 実機でのみ意味を持つ検証。

a = 2.5
b = 0.5
$DM520F = a + b

c = 7.0
d = 2.0
$DM522F = c / d

$DM524F = a + 3

# 実数をワードデバイス (16bit符号付き) へ書くと切り捨てられる
$DM526 = 3.7

# 整数を F デバイスへ書くと実数に変換される
$DM528F = 2

if 1 == 1.0
  $DM530 = 1
else
  $DM530 = 0
end

e = 7
f = 2
$DM532 = e / f
