# 経過時間とクロックパルス
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`)。
# 時刻源だけが違い、三菱は 10ms クロックが `SM409` です。faRuby から見た
# 名前と意味は同じで、`$FARUBY_TICKS` はどちらでもミリ秒です。
#
# `$FARUBY_CLOCK_10MS` / `_100MS` / `_1S` はパルスそのもので、**真偽値**で
# 返ります。値スロットにタグごと写しているためです。
#
# **時間を待つ書き方は差分です。** VM はスキャンごとに戻るので、止まって
# 待つ `sleep` は作れません。回数ではなく**経った時間で**回します。回数だと
# スキャンの速さで待つ長さが変わり、機種によってパルスの山をまたげません。
#
# 300ms 回すので、100ms クロックは 3 周ぶん入れ替わります。
#
# 期待値:
#   $D1010 = 1      経った時間が 0 より大きい (ticks が進んでいる)
#   $D1011 = 1      100ms クロックが真になったところを見た
#   $D1012 = 1      100ms クロックが偽になったところを見た
#   $D1013 = 1      1s クロックが真偽のどちらかで読めた
#   $D1014 = 1      経った時間が 10 の倍数 (10ms ずつ足している)
#
# 調べる用に、期待値を置かないものも書きます。
#
#   $D1015          実際に経った時間 (ミリ秒)
#   $D1016L         回った回数
#
# 実機でのみ意味を持つ検証。**Q と iQ-R で 5 値一致** (SM409 が 10ms、
# SM410 が 100ms であることの裏付けでもあります)。Q では 300ms で 642 回
# まわりました。

t0 = $FARUBY_TICKS

seen_on = false
seen_off = false
i = 0
elapsed = 0
while elapsed < 300
  i = i + 1
  if $FARUBY_CLOCK_100MS
    seen_on = true
  else
    seen_off = true
  end
  elapsed = $FARUBY_TICKS - t0
  # ticks が進まないときの逃げ道。**止まったまま戻らなくなるのを防ぐ**
  elapsed = 300 if i > 200000
end

$D1015 = elapsed
$D1016L = i

$D1010 = 0
$D1011 = 0
$D1012 = 0
$D1013 = 0
$D1014 = 0

$D1010 = 1 if elapsed > 0
$D1011 = 1 if seen_on
$D1012 = 1 if seen_off
$D1013 = 1 if $FARUBY_CLOCK_1S
$D1013 = 1 unless $FARUBY_CLOCK_1S
$D1014 = 1 if elapsed % 10 == 0
