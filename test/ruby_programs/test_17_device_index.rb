# 添字によるデバイスアクセス
#
# 対象機種: KV-5000, KV-X500
#
# デバイスアドレスをコンパイル時ではなく実行時に決める。
# 裸の $DM がデバイス族を表し、添字を付けると実際の読み書きになる。
#
# 添字は「デバイス番号」です。ワードデバイスは表示上のアドレスと一致しますが、
# MR / R / B は一致しません (MR400 は番号 64)。番号空間では線形なので、
# MR415 の次は MR500 になります。
#
# 期待値:
#   $DM600-$DM604      = 0, 10, 20, 30, 40   ループで書き込み
#   $DM610             = 100                 合計 (ループで読み出し)
#   $DM612L (32ビット) = 70000                幅サフィックス付き
#   MR400, MR402       = ON                  ビットデバイス (番号 64, 66)
#   MR401              = OFF
#
# 実機でのみ意味を持つ検証。

# ループで書き込む
i = 0
while i < 5
  $DM[600 + i] = i * 10
  i = i + 1
end

# ループで読み出して合計する
sum = 0
i = 0
while i < 5
  sum = sum + $DM[600 + i]
  i = i + 1
end
$DM610 = sum

# 32ビット幅で書き込む
$DML[612] = 70000

# ビットデバイス。64 は MR400 の番号
# (!= はメソッド呼び出しになるため if で書く)
b = 0
while b < 3
  if b == 1
    $MR[64 + b] = false
  else
    $MR[64 + b] = true
  end
  b = b + 1
end
