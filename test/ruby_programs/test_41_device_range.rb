# 割り付けた範囲を添字で引く
#
# 対象機種: KV-5000, KV-X500
#
# devices: test_41_device_range.devices.rb
#
# **割り付け表にワード数を書くと、添字で引ける範囲になります。** `$DM[i]` は
# DM0 からですが、`map "regs", "DM1100", 8` と書けば `$regs[0]` が DM1100 です。
#
# **VM には足すものがありません。** 添字はデバイス番号にそのまま足され、種別と
# 基点は実行時にシンボル表から引いているので、表の項目を変えるだけで済みます。
# **だからこそ実機で見ます** — 基点の入れ違いは生成時には分からず、黙って
# 隣のデバイスを読み書きします。
#
# **添字はワードで数えます** (`$DM[i]` と同じ)。幅を付けても 1 つ飛びには
# なりません。`$pair[0]` は DM1110-1111、`$pair[2]` は DM1112-1113 です。
#
# **ビットデバイスの番号はメーカーの数え方です。** `MR110` は番号 26 なので、
# `$bits[6]` は番号 32 で `MR200` になります (チャンネルをまたぎます)。
#
# 期待値:
#   $DM1100  = 0        $regs[0]
#   $DM1107  = 70       $regs[7] (範囲の端)
#   $DM1120  = 30       $regs[3] を読み直した値
#   $DM1110L = 100000   $pair[0] (32 ビット)
#   $DM1112L = 200000   $pair[2] (ワードで 2 つ先)
#   $MR110   = 1        $bits[0]
#   $MR115   = 1        $bits[5]
#   $MR200   = 1        $bits[6] (番号 32。チャンネルをまたいだ)
#
# 実機でのみ意味を持つ検証。

8.times { |i| $regs[i] = i * 10 }
$DM1120 = $regs[3]

$pair[0] = 100000
$pair[2] = 200000

$bits[0] = true
$bits[5] = true
$bits[6] = true
