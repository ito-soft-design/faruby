# any? / all? / none?
#
# 対象機種: iQ-R
#
# **キーエンス版からデバイス名だけを置き換えたものです** (`DM` → `D`)。
# **Q では走りません。** 配列とハッシュを外しているためで、
# 述語はどちらかをレシーバに取ります。
#
# **新しいのはブロックの戻り値を見ることだけです。** ほかの反復
# (`each` / `times` / `upto` / `loop`) はブロックの値を捨てます — `each` は
# レシーバがそのまま呼び出しの値になり、`loop` は `break` でしか終わりません。
# 述語は毎回の値が答えになりうるので、`OP_RETURN` で見ます。
#
# **ここで見たいのは打ち切りです。** 全部回っても答えは同じなので、
# 回数を数えないと「打ち切っているつもりで回り切っている」ことに
# 気づけません ($D1183 と $D1188)。
#
# **空のときも見ます。** 1 回も回らないとフレームを積まないので、答えを
# 書く場所が別です。書き忘れるとレシーバ (配列) がそのまま返り、
# **Ruby では配列は真なので `any?` が常に真**になります。
#
# **置き場は増えていません。** 答えは R[0] (レシーバの位置) に書きます。
# 打ち切る瞬間はもう要素を取り出さないので、レシーバを潰してよいからです。
#
# 期待値:
#   $D1180 = 1        any? は見つかれば真
#   $D1181 = 0        any? は見つからなければ偽
#   $D1182 = 0        空の any? は偽 (レシーバを返していない)
#   $D1183 = 3        any? は見つかった時点で打ち切る (全部回ると 6)
#   $D1184 = 1        all? は全部真なら真
#   $D1185 = 0        all? は偽が混ざれば偽
#   $D1186 = 1        空の all? は真
#   $D1187 = 1        none? は 1 つも無ければ真
#   $D1188 = 3        all? は偽を見た時点で打ち切る
#   $D1189 = 1        ブロックが 0 を返しても真 (Ruby と同じ)
#   $D1190 = 0        ブロックが nil を返せば偽
#   $D1191 = 1        ハッシュの any? は鍵と値を渡す
#   $D1192 = 0        ハッシュの all?
#   $D1193 = 1        入れ子の any? (内側の判定が外側に漏れない)
#
# **ブロックは 1 つの irep です。** 上限が 16 なので、`each` を壊して
# いないことの確認は入りません (test_21_arrays.rb が見ています)。
#
# 実機でのみ意味を持つ検証。

a = [1, 2, 3]

$D1180 = a.any? { |x| x == 2 } ? 1 : 0
$D1181 = a.any? { |x| x == 9 } ? 1 : 0

empty = []
$D1182 = empty.any? { |x| true } ? 1 : 0

# 打ち切っていること。2 で止まれば 1 + 2 = 3、回り切ると 6
n = 0
a.any? do |x|
  n = n + x
  x == 2
end
$D1183 = n

$D1184 = a.all? { |x| x > 0 } ? 1 : 0
$D1185 = a.all? { |x| x > 1 } ? 1 : 0
$D1186 = empty.all? { |x| false } ? 1 : 0
$D1187 = a.none? { |x| x == 9 } ? 1 : 0

# all? も同じ。2 で外れれば 1 + 2 = 3
m = 0
a.all? do |x|
  m = m + x
  x < 2
end
$D1188 = m

$D1189 = a.any? { |x| 0 } ? 1 : 0
$D1190 = a.any? { |x| nil } ? 1 : 0

h = { 1 => 10, 2 => 20 }
$D1191 = h.any? { |k, v| v == 20 } ? 1 : 0
$D1192 = h.all? { |k, v| v > 15 } ? 1 : 0

b = [8, 9]
$D1193 = a.any? { |x| b.any? { |y| x + y == 11 } } ? 1 : 0
