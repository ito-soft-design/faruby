# デバイスの読み書き
#
# 対象機種: Q
#
# **キーエンス版の写しではありません。** 種別が違うので書き下ろしています
# (`DM` → `D`、`MR` → `M`)。キーエンスの `R` はビットデバイスですが、三菱の
# `R` はワードデバイスです。
#
# **ビットデバイスは真偽値で返ります。** 期待値は数で書くので、いったん
# ワードデバイスに移してから確かめます (test_32_bit_devices_q.rb と同じ形)。
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 期待値:
#   $D3100 = 42     ワードデバイスに書いて読む
#   $D3101 = 43     ビットデバイスを整数として足す (ON は 1)
#   $D3102 = 1      非0 を書くと ON になる (43 でも 1)

$D3100 = 42
$M10 = 1
$M200 = $D3100 + $M10

$D3101 = $D3100 + $M10
$D3102 = 0
$D3102 = 1 if $M200
