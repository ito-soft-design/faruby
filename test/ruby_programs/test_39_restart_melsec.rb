# 電源を入れ直したときの再始動
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`)。
#
# **期待値を書いていません。** 終わらないプログラムなので `rake hw` では
# 確かめられず、電源を切る操作も要ります。手順は
# [doc/testing.md](../../doc/testing.md#電源を入れ直したときの再始動)。
#
# `$D1030` は走り出した回数です。**D は電源を切っても残る**ので、
# 入れ直して 1 増えていれば先頭から走り直したことになります。
#
# `break` を書いていないので終わりません。STATUS は実行中のままで、
# 電源を切ったときの状態がそのまま「実行中だった」になります。
#
# 見るもの:
#   $D1030   走り出した回数。入れ直すたびに 1 増える
#   $D1031   同じ値。**ループが回っている印** (先頭だけで決まる値を書く)
#   $D1032L  経過ミリ秒。動いていれば増え続ける

$D1030 = $D1030 + 1
started = $D1030

loop do
  $D1031 = started
  $D1032L = $FARUBY_TICKS
end
