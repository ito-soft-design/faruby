# インスタンス変数 (@)
#
# 対象機種: KV-5000, KV-X500
#
# `@foo` は汎用グローバル変数と同じ値スロットに置いています。**self が 1 つ
# しか無いので、名前ごとに 1 枠で足ります** — クラスが無いので、トップレベルも
# メソッドの中もブロックの中も self は `main` です。Ruby でもトップレベルの
# `@foo` は `main` のインスタンス変数なので、近似ではありません。
#
# **命令は中身を持ちません。** `OP_GETIV` (0x19) / `OP_SETIV` (0x1A) は
# `OP_GETGV` / `OP_SETGV` と同じ `BB` 形式で、オペコードを書き替えて枝へ
# 落とすだけです (`OP_SSEND` と同じ前処理の形)。
#
# **実機で見たいのは値スロットの経路に正しく載っているか**です。前処理が
# 落ちる先を間違えていれば、読み書きそのものが別の場所へ行きます。
#
# **`nil` から始まるので `||=` が効きます。** デバイスに割り付けた変数との
# 違いで、デバイスは数値しか持てないので読んだ 0 が真になり、一度も代入
# されません。
#
# 期待値:
#   $DM1130 = 1        トップレベルの読み書き
#   $DM1131 = 3        メソッドの中から同じ @n (3 回呼んだ)
#   $DM1132 = 10       ブロックの中から同じ @sum (0+1+2+3+4)
#   $DM1133 = 3        配列を持てる (@a.length)
#   $DM1134 = 3        文字列を持てる (@s.length)
#   $DM1135 = 1        実数を持てる (@f > 1.0)
#   $DM1136 = 7        @once ||= 7 が効く
#   $DM1137 = 1        $n と @n は別の枠 ($n の側)
#   $DM1138 = 2        同上 (@n の側)
#
# 実機でのみ意味を持つ検証。

@n = 0
@n = @n + 1
$DM1130 = @n

@n = 0

def bump
  @n = @n + 1
end

bump
bump
bump
$DM1131 = @n

@sum = 0
5.times { |i| @sum = @sum + i }
$DM1132 = @sum

@a = [1, 2, 3]
@s = "abc"
@f = 1.5
$DM1133 = @a.length
$DM1134 = @s.length
$DM1135 = 1 if @f > 1.0

@once ||= 7
$DM1136 = @once

$n = 1
@n = 2
$DM1137 = $n
$DM1138 = @n
