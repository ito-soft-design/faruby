# 整数のビットを取る (Integer#[])
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# **PLC はビットを扱う場面が多いので、`(n >> i) & 1` と書かずに済ませます。**
# `n[i]` は OP_GETIDX になり、配列や文字列と同じ命令を通ります。
#
# Ruby と同じで、添字が負なら 0、桁数以上なら符号ビットです (上は無限に
# 符号が続いているものとして扱います)。
#
# 期待値:
#   $D3140 = 1       5[0]  下位ビット
#   $D3141 = 0       5[1]
#   $D3142 = 1       5[2]
#   $D3143 = 0       5[3]
#   $D3144 = 1       添字を変数で渡す (n[m], m = 2)
#   $D3145 = 0       5[31] 正の数の符号ビット
#   $D3146 = 1       (-2)[31] 負の数の符号ビット
#   $D3147 = 1       (-1)[40] 桁数を超えても符号が続く
#   $D3148 = 0       5[-1] 負の添字は 0
#   $D3149 = 1       デバイスから読んだ値のビット ($D3130 = 6 の 1 ビット目)
#
# 実機でのみ意味を持つ検証。

n = 5
$D3140 = n[0]
$D3141 = n[1]
$D3142 = n[2]
$D3143 = n[3]

m = 2
$D3144 = n[m]

$D3145 = n[31]

p = -2
$D3146 = p[31]

q = -1
$D3147 = q[40]

$D3148 = n[-1]

$D3130 = 6
w = $D3130
$D3149 = w[1]
