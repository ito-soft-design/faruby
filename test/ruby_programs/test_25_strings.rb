# 文字列のリテラルとデバイスへの書き込み
#
# 対象機種: KV-5000, KV-X500
#
# 実体は配列プールのスロット。見出しの後ろに 1 ワード 2 バイトで詰め、
# **先の文字が上位バイト**。KV-5000 の文字列デバイスと同じ並びなので、
# デバイスへの書き込みはワード単位の写しで済む。
#
# バイト列は変換しない。ソースの文字コードがそのままデバイスへ出る。
#
# 書き方は 2 つ。
#   $DM880   = "abc"    終端付き。バイト列 + 0
#   $DM887T6 = "abc"    固定長。余りは FARUBY_STR_FILL、はみ出す分は切り詰め
#
# 期待値 (16ビット符号なしで読む):
#   $DM880U = 24930   "ab"      終端付き
#   $DM881U = 25344   "c\0"
#   $DM883U = 24930   "ab"      偶数バイトは終端に 1 ワード余分に要る
#   $DM884U = 25444   "cd"
#   $DM885U = 0       終端
#   $DM887U = 24930   "ab"      固定長。足りない桁は 0x20 で埋める
#   $DM888U = 25376   "c "
#   $DM889U = 8224    "  "
#   $DM891U = 16706   "AB"      ちょうど。終端は書かない
#   $DM892U = 17220   "CD"
#   $DM893U = 17734   "EF"
#   $DM894U = 1234    次の桁にはみ出していない (書く前に置いた印)
#   $DM895U = 24930   "ab"      はみ出す分は切り詰める
#   $DM896U = 25444   "cd"
#   $DM897U = 1234    切り詰めた先を触っていない (書く前に置いた印)
#   $DM898U = 24930   "ab"      桁数が奇数
#   $DM899U = 8224    "  "
#   $DM900U = 8192    " \0"     最後のワードの下位バイトは桁の外なので 0
#   $DM902U = 0       空文字列は終端だけ
#   $DM904U = 58241   UTF-8 の "あ" 1 バイト目と 2 バイト目
#   $DM905U = 33280   3 バイト目と終端
#   $DM907U = 26729   "hi"      変数に入れた文字列
#   $DM908U = 0       終端
#   $DM909U = 26729   "hi"      同じ文字列を固定長でも書ける
#   $DM910U = 8224    "  "
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルはプールを 1 スロット使う。16 スロットしかないので、
# 行を増やすときは残りに気をつけること。

FARUBY_STR_FILL = 0x20

$DM880 = "abc"
$DM883 = "abcd"
$DM887T6 = "abc"

# ちょうど収まる桁。終端を書くと次の桁にはみ出す
$DM894 = 1234
$DM891T6 = "ABCDEF"

# 桁からはみ出す文字列は切り詰める。止めない
$DM897 = 1234
$DM895T4 = "abcdefgh"

$DM898T5 = "ab"

$DM902 = 1234
$DM902 = ""

# バイト列は変換しない。UTF-8 のソースなら UTF-8 が出る
$DM904 = "あ"

s = "hi"
$DM907 = s
$DM909T4 = s
