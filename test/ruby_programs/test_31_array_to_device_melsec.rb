# 配列とデバイスの間で写す
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# `$D100 = a` で a の要素を DM100 から順に書く。**刻みは幅で決まる。**
# `.S` / `.U` は 1 ワード、`.L` / `.D` / `.F` は 2 ワードずつ進む。
#
# ビットデバイスは 1 ワードが 16 ビットにあたるので、`$ML[64] = a` は
# 64・96・128 ビット目へ書く。**個別ビット (幅なし) には書けない。**
# 1 要素が何ビットか決まらないため。
#
# 要素は数値だけ。中に文字列や配列があると止まる。ハッシュも書けない。
#
# 期待値:
#   $D940 = 11      16 ビット。3 要素が並ぶ
#   $D941 = 22
#   $D942 = 33
#   $D944L = 100    32 ビットは 2 ワードずつ
#   $D946L = 200
#   $D950F = 1.5    実数も書ける
#   $D952F = 2.5
#   $D954 = 7       添字を付けた形も同じ
#   $D955 = 8
#   $D960L = 5      ビットデバイスは 16 ビット刻み。書いて読み戻す
#   $D962L = 6
#   $D964 = 3       $D[940, 3] で 3 個読む
#   $D965 = 11      その 0 番目
#   $D966 = 33      その 2 番目
#   $D967 = 100     32 ビットも同じ
#   $D968 = 1       個数が負なら nil (Ruby と同じ)
#
# 実機でのみ意味を持つ検証。

a = [11, 22, 33]
$D940 = a

b = [100, 200]
$D944L = b

c = [1.5, 2.5]
$D950F = c

i = 0
$D[954 + i] = [7, 8]

# ビットデバイス。幅を付けたときだけ書ける
$ML[64 + i] = [5, 6]
$D960L = $ML[64]
$D962L = $ML[96]

# デバイスから配列へ。個数を書く
d = $D[940, 3]
$D964 = d.length
$D965 = d[0]
$D966 = d[2]

e = $DL[944, 2]
$D967 = e[0]

f = $D[940, -1]
$D968 = 0
if f == nil
  $D968 = 1
end
