# 組み込みメソッド
#
# 対象機種: KV-5000, KV-X500
#
# OP_SEND の限定実装。呼び出しフレームを作らず、その場で計算して返す。
# メソッド名はホスト側で番号に解決済みで、VM は整数の分岐で振り分ける。
#
# 期待値:
#   $DM620 = 1     1 != 2
#   $DM621 = 0     1 != 1.0        数値は型が違っても値で比べる
#   $DM622 = 1     nil != false    型が違えば等しくない
#   $DM623 = 1     !nil
#   $DM624 = 0     !0              Ruby では 0 も真
#   $DM625 = 1     7 % 3
#   $DM626 = 2     -7 % 3          符号は除数に合う
#   $DM627 = -2    7 % -3
#   $DM628 = 3     (-3).abs
#   $DM629 = -2    (-2.7).to_i     0 方向へ切り捨て
#   $DM630 = -3    (-2.7).floor    -∞ 方向
#   $DM631 = 3     2.5.round       0 から遠い方へ
#   $DM632 = -3    (-2.5).round
#   $DM634F = 2.5  (-2.5).abs      実数は型が変わらない
#   $DM636F = 3.0  3.to_f
#
# 32ビットで読む必要はない ($DM620 等は16ビット符号付き)。
# $DM634F と $DM636F は 2 ワードずつ占有する。
#
# 実機でのみ意味を持つ検証。

a = 1
b = 2
c = 1.0

$DM620 = 0
if a != b
  $DM620 = 1
end

$DM621 = 0
if a != c
  $DM621 = 1
end

n = nil
f = false
$DM622 = 0
if n != f
  $DM622 = 1
end

$DM623 = 0
if !n
  $DM623 = 1
end

z = 0
$DM624 = 0
if !z
  $DM624 = 1
end

# 剰余。定数どうしは mrbc が畳み込むため変数を挟む
p = 7
q = 3
$DM625 = p % q

p = -7
$DM626 = p % q

p = 7
q = -3
$DM627 = p % q

# 数値変換
v = -3
$DM628 = v.abs

w = -2.7
$DM629 = w.to_i
$DM630 = w.floor

r = 2.5
$DM631 = r.round

r = -2.5
$DM632 = r.round
$DM634F = r.abs

t = 3
$DM636F = t.to_f
