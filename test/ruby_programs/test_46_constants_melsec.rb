# 定数とクラス変数
#
# 対象機種: Q, iQ-R
#
# **キーエンス版からデバイス名だけを置き換えたものです** (`DM` → `D`)。
#
# **どちらも汎用グローバルの値スロットに入ります。** `$foo` と同じ場所で、
# VM に足したのは前処理 2 つ (`OP_GETCV` / `OP_SETCV` が `OP_GETGV` /
# `OP_SETGV` の枝へ落ちる) と、`OP_GETCONST` / `OP_SETCONST` の種別による
# 振り分けだけです。
#
# **ここで見たいのは種別の振り分けです。** クラス名と定数が同じ
# `OP_GETCONST` で来るので、取り込み漏れがあると**どちらかが相手の経路を
# 通ります。** 以前は定数がクラスとして登録され、`$D0 = FOO` が 7 ではなく
# クラス番号の 1 を書いて**エラーにならずに通っていました** — 同じ形の
# 間違いは実機でも静かに出ます。
#
# **クラスごとに別の枠であることも見ます。** 名前だけで枠を取る実装が
# 入っていると `C` と `D` の `@@n` が混ざり、最後に書いた値が両方から
# 見えます。これもエラーになりません。
#
# **配列も文字列も使いません。** MELSEC Q は 3 つの型を外していますが
# クラスは載っているので、整数だけで書いてあります。
#
# 期待値:
#   $D1170 = 7        定数を作って読める (クラス番号 1 ではない)
#   $D1171 = 22       定数が 2 つ以上あっても混ざらない
#   $D1172 = 12       定数は式の結果を持てる
#   $D1173 = 9        定数をメソッドの中から読める
#   $D1174 = 5        クラスの中の定数をそのクラスのメソッドから読める
#   $D1175 = 2        クラス変数はオブジェクトをまたいで共有される
#   $D1176 = 1        C の @@n
#   $D1177 = 2        D の @@n (C と別の枠)
#   $D1178 = 1        同じオブジェクトの @n (クラス変数と別物)
#   $D1179 = 3        クラス名はクラスのまま使える
#
# 実機でのみ意味を持つ検証。

FOO = 7
A = 11
B = 22
N = 3 * 4
LIMIT = 9

class Holder
  INNER = 5

  def inner
    INNER
  end

  def limit
    LIMIT
  end
end

class Counter
  def inc
    @@n = (@@n || 0) + 1
  end

  def mark
    @@n = 1
    @n = 1
    @@n
  end

  def iv
    @n
  end

  def three
    3
  end
end

class Other
  def mark
    @@n = 2
    @@n
  end
end

$D1170 = FOO
$D1171 = B
$D1172 = N

h = Holder.new
$D1173 = h.limit
$D1174 = h.inner

# **2 つのオブジェクトで 1 つの @@n を数えます**
Counter.new.inc
$D1175 = Counter.new.inc

# **クラスをまたいだときに混ざらないこと。** 先に C、後に D を書く
c = Counter.new
$D1176 = c.mark
$D1177 = Other.new.mark

# D が書いた後でも C の @n は動かない (クラス変数と別物)
$D1178 = c.iv

$D1179 = c.three
