# 配列をデバイスへ写す
#
# `$DM100 = a` で a の要素を DM100 から順に書く。**刻みは幅で決まる。**
# `.S` / `.U` は 1 ワード、`.L` / `.D` / `.F` は 2 ワードずつ進む。
#
# ビットデバイスは 1 ワードが 16 ビットにあたるので、`$MRL[64] = a` は
# 64・96・128 ビット目へ書く。**個別ビット (幅なし) には書けない。**
# 1 要素が何ビットか決まらないため。
#
# 要素は数値だけ。中に文字列や配列があると止まる。ハッシュも書けない。
#
# 期待値:
#   $DM940 = 11      16 ビット。3 要素が並ぶ
#   $DM941 = 22
#   $DM942 = 33
#   $DM944L = 100    32 ビットは 2 ワードずつ
#   $DM946L = 200
#   $DM950F = 1.5    実数も書ける
#   $DM952F = 2.5
#   $DM954 = 7       添字を付けた形も同じ
#   $DM955 = 8
#   $DM960L = 5      ビットデバイスは 16 ビット刻み。書いて読み戻す
#   $DM962L = 6
#
# 実機でのみ意味を持つ検証。

a = [11, 22, 33]
$DM940 = a

b = [100, 200]
$DM944L = b

c = [1.5, 2.5]
$DM950F = c

i = 0
$DM[954 + i] = [7, 8]

# ビットデバイス。幅を付けたときだけ書ける
$MRL[64 + i] = [5, 6]
$DM960L = $MRL[64]
$DM962L = $MRL[96]
