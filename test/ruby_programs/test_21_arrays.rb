# 配列の生成と添字アクセス
#
# 対象機種: KV-5000, KV-X500
#
# 実体は固定数のスロットを並べた配列プールに置き、レジスタには型タグと
# スロット番号だけが入る。スロットは順に渡して返さないため、ループの中で
# 作り続けるといずれ「配列の領域が足りない」で止まる。
#
# 添字の読みは範囲外でも nil (Ruby と同じ)。書きは要素数を超えると配列を
# 伸ばし、間を nil で埋める。ただし容量は固定なので超えるとエラーになる。
#
# 期待値:
#   $DM710 = 22     a[1]
#   $DM711 = 11     a[0]
#   $DM712 = 33     a[-1] は最後の要素
#   $DM713 = 1      範囲外の読みは nil
#   $DM714 = 99     a[0] = 99
#   $DM715 = 99     要素数を超える位置へ代入すると伸びる
#   $DM716 = 1      伸ばした隙間は nil
#   $DM717 = 3      入れ子 a[1][0]
#   $DM718 = 6      ループで読む
#   $DM719 = 3      ループで書く
#   $DM720 = 8      メソッドから返した配列
#   $DM721 = 42     デバイスの値を要素にする
#   $DM722 = 3      length
#   $DM723 = 3      size
#   $DM724 = 0      空配列の length
#   $DM725 = 5      << で足す
#   $DM726 = 2      << を重ねる
#   $DM727 = 9      push
#   $DM728 = 5      ループで詰める
#   $DM729 = 12     詰めてから合計する
#   $DM731 = 66     each は要素を渡す (添字なら 0+1+2 = 3 になる)
#
# 実機でのみ意味を持つ検証。
#
# プールは 16 スロットしかないため、配列を新しく作る行を増やすと
# 「配列の領域が足りない」で止まります。既存の配列を使い回してください。

a = [11, 22, 33]
$DM710 = a[1]
$DM711 = a[0]
$DM712 = a[-1]

$DM713 = 0
if a[5] == nil
  $DM713 = 1
end

b = [11, 22]
b[0] = 99
$DM714 = b[0]

c = [11]
c[2] = 99
$DM715 = c[2]
$DM716 = 0
if c[1] == nil
  $DM716 = 1
end

d = [[1, 2], [3, 4]]
$DM717 = d[1][0]

e = [1, 2, 3]
s = 0
3.times do |i|
  s = s + e[i]
end
$DM718 = s

f = [0, 0, 0]
3.times do |i|
  f[i] = i + 1
end
$DM719 = f[2]

def make
  [7, 8]
end
g = make
$DM720 = g[1]

$DM730 = 42
h = [$DM730]
$DM721 = h[0]

# プールは 16 スロットしかないため、新しく作らず既存の配列を使い回す
$DM722 = a.length
$DM723 = a.size

j = []
$DM724 = j.length
j << 5
$DM725 = j[0]
j << 6
$DM726 = j.length

m = [1]
m.push(9)
$DM727 = m[1]

n = []
5.times do |x|
  n << x
end
$DM728 = n.length

p = []
4.times do |x|
  p << x * 2
end
t = 0
4.times do |x|
  t = t + p[x]
end
$DM729 = t

# each はブロックに添字ではなく要素を渡す。
# 添字が渡っていれば 0+1+2 = 3 になるので取り違えを検出できる
t = 0
a.each do |v|
  t = t + v
end
$DM731 = t
