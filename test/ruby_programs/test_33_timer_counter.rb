# タイマ・カウンタの読み取り
#
# **接点は読み取り専用です。** タイムアップ・カウントアップで決まるもので、
# `$T0 = true` はエラーで停止します (別に確かめます)。幅を付けると現在値に
# なります (`$T0S`)。
#
# **KV-X500 では読み取りもできません。** KV Studio の変換が通らないため、
# 生成コードから分岐ごと外してあります。X500 で `$T0` を使うと実行時に
# デバイスアクセスのエラーで止まります。それが正しい動きです。
#
# 対象機種: KV-5000
#
# 期待値:
#   $DM126 = 0       タイマの接点は読める (タイムアップしていない)
#   $DM127 = 0       カウンタの接点も読める (カウントアップしていない)
#
# 実機でのみ意味を持つ検証。

$DM126 = 0
$DM126 = 1 if $T0

$DM127 = 0
$DM127 = 1 if $C0
