# 文字列の比較と連結
#
# **`==` は中身で比べる。** レジスタに入っているのはスロット番号なので、
# 同じ内容が別のスロットにあると番号では等しくならない。バイト数が同じなら
# ワード単位で比べる (並びが揃っているので回数はバイト数の半分)。
#
# ハッシュの鍵も同じ判定にする。文字列の鍵はスロットが違っても同じ鍵。
#
# 連結は 2 つ。`+` は新しいスロットを取り、`OP_STRCAT` (式展開) は
# 継ぎ足す先をそのまま伸ばす。継ぎ足す先の長さが奇数だとワードの途中から
# 始まるので、そこはバイト単位で書く。
#
# 期待値:
#   $DM960 = 1       別のスロットの同じ内容は等しい
#   $DM961 = 1       長さが違えば等しくない
#   $DM962 = 7       文字列の鍵で引ける
#   $DM963 = 9       新しい文字列の鍵を足せる
#   $DM970U = 24930  "ab"   a + b
#   $DM971U = 25444  "cd"
#   $DM972U = 0      終端
#   $DM974U = 28792  "px"   式展開 "p#{c}q"
#   $DM975U = 28928  "q\0"
#   $DM978U = 24930  "ab"   + は左側を変えない
#   $DM979U = 0      終端
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと `+` の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

FARUBY_STR_FILL = 0x20

s = "hello"
t = "hello"

$DM960 = 0
if s == t
  $DM960 = 1
end

$DM961 = 0
if s != "hell"
  $DM961 = 1
end

# 文字列の鍵。書いたときと引くときで別のスロットになる
h = { "x" => 7 }
$DM962 = h["x"]
h["z"] = 9
$DM963 = h["z"]

a = "ab"
b = "cd"
$DM970 = a + b

c = "x"
$DM974 = "p#{c}q"

# + は新しいスロットを取るので、左側は変わらない
$DM978 = a
