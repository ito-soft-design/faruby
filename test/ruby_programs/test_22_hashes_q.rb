# ハッシュの生成と添字アクセス
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 実体は配列プールのスロット 2 つ (鍵の配列と値の配列)。レジスタには型タグと
# スロット番号 2 つが入る。検索は鍵の配列の線形走査で、一致は型と値の両方。
#
# 無い鍵は nil、既にある鍵は値だけ差し替え、新しい鍵は両方の末尾に足す。
#
# 期待値:
#   $D3740 = 2      h[:b]
#   $D3741 = 1      h[:a]
#   $D3742 = 1      無い鍵は nil
#   $D3743 = 3      新しい鍵は足される
#   $D3744 = 9      既にある鍵は差し替わる
#   $D3745 = 2      差し替えても他の鍵は変わらない
#   $D3746 = 1      3 組の 1 つ目 (オペランドが組の数であることの確認)
#   $D3747 = 2      3 組の 2 つ目
#   $D3748 = 3      3 組の 3 つ目
#   $D3749 = 10     整数の鍵
#   $D3750 = 20     整数の鍵
#   $D3751 = 1      空ハッシュはどの鍵も nil
#   $D3752 = 5      空ハッシュに足せる
#   $D3753 = 8      メソッドが返したハッシュ
#   $D3754 = 8      値が配列
#   $D3755 = 20     ループで詰める
#   $D3756 = 9      ブロックの中から引く (シンボルが irep をまたぐ)
#
# 実機でのみ意味を持つ検証。
#
# ハッシュ 1 つがプールを 2 スロット使うため、全 16 スロットでは
# ハッシュ 8 個が限度です。新しく作らず既存のものを使い回してください。

a = { a: 1, b: 2 }
$D3740 = a[:b]
$D3741 = a[:a]

$D3742 = 0
if a[:zz] == nil
  $D3742 = 1
end

a[:c] = 3
$D3743 = a[:c]

a[:a] = 9
$D3744 = a[:a]
$D3745 = a[:b]

# 組が 3 つ。OP_HASH のオペランドがレジスタ数ではなく組の数であること
b = { x: 1, y: 2, z: 3 }
$D3746 = b[:x]
$D3747 = b[:y]
$D3748 = b[:z]

c = { 1 => 10, 2 => 20 }
