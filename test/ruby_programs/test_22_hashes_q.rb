# ハッシュの生成と添字アクセス
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# 実体は配列プールのスロット 2 つ (鍵の配列と値の配列)。レジスタには型タグと
# スロット番号 2 つが入る。検索は鍵の配列の線形走査で、一致は型と値の両方。
#
# 無い鍵は nil、既にある鍵は値だけ差し替え、新しい鍵は両方の末尾に足す。
#
# 期待値:
#   $D740 = 2      h[:b]
#   $D741 = 1      h[:a]
#   $D742 = 1      無い鍵は nil
#   $D743 = 3      新しい鍵は足される
#   $D744 = 9      既にある鍵は差し替わる
#   $D745 = 2      差し替えても他の鍵は変わらない
#   $D746 = 1      3 組の 1 つ目 (オペランドが組の数であることの確認)
#   $D747 = 2      3 組の 2 つ目
#   $D748 = 3      3 組の 3 つ目
#   $D749 = 10     整数の鍵
#   $D750 = 20     整数の鍵
#   $D751 = 1      空ハッシュはどの鍵も nil
#   $D752 = 5      空ハッシュに足せる
#   $D753 = 8      メソッドが返したハッシュ
#   $D754 = 8      値が配列
#   $D755 = 20     ループで詰める
#   $D756 = 9      ブロックの中から引く (シンボルが irep をまたぐ)
#
# 実機でのみ意味を持つ検証。
#
# ハッシュ 1 つがプールを 2 スロット使うため、全 16 スロットでは
# ハッシュ 8 個が限度です。新しく作らず既存のものを使い回してください。

a = { a: 1, b: 2 }
$D740 = a[:b]
$D741 = a[:a]

$D742 = 0
if a[:zz] == nil
  $D742 = 1
end

a[:c] = 3
$D743 = a[:c]

a[:a] = 9
$D744 = a[:a]
$D745 = a[:b]

# 組が 3 つ。OP_HASH のオペランドがレジスタ数ではなく組の数であること
b = { x: 1, y: 2, z: 3 }
$D746 = b[:x]
$D747 = b[:y]
$D748 = b[:z]

c = { 1 => 10, 2 => 20 }
$D749 = c[1]
$D750 = c[2]

d = {}
$D751 = 0
if d[:a] == nil
  $D751 = 1
end
d[:a] = 5
$D752 = d[:a]

def make
  { k: 8 }
end
e = make
$D753 = e[:k]

f = { v: [7, 8] }
$D754 = f[:v][1]

# 新しく作らず d を使い回す。整数の鍵はシンボルの :a と型が違うのでぶつからない
3.times do |i|
  d[i] = i * 10
end
$D755 = d[2]

# ブロックの中の :a はトップレベルの :a と別の irep にある
2.times do
  $D756 = a[:a]
end
