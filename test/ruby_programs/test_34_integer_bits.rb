# 整数のビットを取る (Integer#[])
#
# **PLC はビットを扱う場面が多いので、`(n >> i) & 1` と書かずに済ませます。**
# `n[i]` は OP_GETIDX になり、配列や文字列と同じ命令を通ります。
#
# Ruby と同じで、添字が負なら 0、桁数以上なら符号ビットです (上は無限に
# 符号が続いているものとして扱います)。
#
# 期待値:
#   $DM140 = 1       5[0]  下位ビット
#   $DM141 = 0       5[1]
#   $DM142 = 1       5[2]
#   $DM143 = 0       5[3]
#   $DM144 = 1       添字を変数で渡す (n[m], m = 2)
#   $DM145 = 0       5[31] 正の数の符号ビット
#   $DM146 = 1       (-2)[31] 負の数の符号ビット
#   $DM147 = 1       (-1)[40] 桁数を超えても符号が続く
#   $DM148 = 0       5[-1] 負の添字は 0
#   $DM149 = 1       デバイスから読んだ値のビット ($DM130 = 6 の 1 ビット目)
#
# 実機でのみ意味を持つ検証。

n = 5
$DM140 = n[0]
$DM141 = n[1]
$DM142 = n[2]
$DM143 = n[3]

m = 2
$DM144 = n[m]

$DM145 = n[31]

p = -2
$DM146 = p[31]

q = -1
$DM147 = q[40]

$DM148 = n[-1]

$DM130 = 6
w = $DM130
$DM149 = w[1]
