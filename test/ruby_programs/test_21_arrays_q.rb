# 配列の生成と添字アクセス
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 実体は固定数のスロットを並べた配列プールに置き、レジスタには型タグと
# スロット番号だけが入る。スロットは順に渡して返さないため、ループの中で
# 作り続けるといずれ「配列の領域が足りない」で止まる。
#
# 添字の読みは範囲外でも nil (Ruby と同じ)。書きは要素数を超えると配列を
# 伸ばし、間を nil で埋める。ただし容量は固定なので超えるとエラーになる。
#
# 期待値:
#   $D3710 = 22     a[1]
#   $D3711 = 11     a[0]
#   $D3712 = 33     a[-1] は最後の要素
#   $D3713 = 1      範囲外の読みは nil
#   $D3714 = 99     a[0] = 99
#   $D3715 = 99     要素数を超える位置へ代入すると伸びる
#   $D3716 = 1      伸ばした隙間は nil
#   $D3717 = 3      入れ子 a[1][0]
#   $D3718 = 6      ループで読む
#   $D3719 = 3      ループで書く
#   $D3720 = 8      メソッドから返した配列
#   $D3721 = 42     デバイスの値を要素にする
#   $D3722 = 3      length
#   $D3723 = 3      size
#   $D3724 = 0      空配列の length
#   $D3725 = 5      << で足す
#   $D3726 = 2      << を重ねる
#   $D3727 = 9      push
#   $D3728 = 5      ループで詰める
#   $D3729 = 12     詰めてから合計する
#   $D3731 = 66     each は要素を渡す (添字なら 0+1+2 = 3 になる)
#
# 実機でのみ意味を持つ検証。
#
# プールは 16 スロットしかないため、配列を新しく作る行を増やすと
# 「配列の領域が足りない」で止まります。既存の配列を使い回してください。

a = [11, 22, 33]
$D3710 = a[1]
$D3711 = a[0]
$D3712 = a[-1]

$D3713 = 0
if a[5] == nil
  $D3713 = 1
end

b = [11, 22]
b[0] = 99
$D3714 = b[0]

c = [11]
c[2] = 99
$D3715 = c[2]
$D3716 = 0
if c[1] == nil
  $D3716 = 1
end

d = [[1, 2], [3, 4]]
$D3717 = d[1][0]

e = [1, 2, 3]
s = 0
3.times do |i|
  s = s + e[i]
end
$D3718 = s

f = [0, 0, 0]
3.times do |i|
  f[i] = i + 1
end
$D3719 = f[2]

def make
  [7, 8]
end
g = make
$D3720 = g[1]

$D3730 = 42
h = [$D3730]
$D3721 = h[0]

# プールは 16 スロットしかないため、新しく作らず既存の配列を使い回す
$D3722 = a.length
$D3723 = a.size

j = []
$D3724 = j.length
j << 5
$D3725 = j[0]
j << 6
$D3726 = j.length

m = [1]
m.push(9)
$D3727 = m[1]

n = []
5.times do |x|
  n << x
end
$D3728 = n.length

p = []
4.times do |x|
  p << x * 2
end
t = 0
4.times do |x|
  t = t + p[x]
end
$D3729 = t

# each はブロックに添字ではなく要素を渡す。
# 添字が渡っていれば 0+1+2 = 3 になるので取り違えを検出できる
t = 0
a.each do |v|
  t = t + v
end
$D3731 = t
