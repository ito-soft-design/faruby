# 整数のビット演算
#
# 対象機種: KV-5000, KV-X500
#
# PLC はビットを立てたり落としたりする処理が多い。KV スクリプトの
# `AND` / `OR` / `XOR` / `NOT` はワードの演算子としてそのまま書ける。
# **条件式の連結には使えない**ので、そちらは今までどおり入れ子の `IF`。
# シフトは `SLA(元, 桁数, 先)` / `SRA(元, 桁数, 先)` の文。
#
# 32 ビット符号付きで計算する。整数だけで、実数を渡すと止まる。
#
# `<<` は整数なら左シフト、文字列と配列なら継ぎ足し (Ruby と同じ)。
#
# 期待値:
#   $DM940 = 8       12 & 10
#   $DM941 = 14      12 | 10
#   $DM942 = 6       12 ^ 10
#   $DM943 = -6      ~5
#   $DM944 = 48      12 << 2
#   $DM945 = 3       12 >> 2
#   $DM946 = -3      -5 >> 1   切り下げ (Ruby と同じ)
#   $DM947 = 1       ビットが立っているかを見る
#   $DM948 = 0       落とした後
#   $DM950L = 65536  1 << 16   32 ビットで計算する
#   $DM952 = -10     -5 << 1   値が負でもよい
#   $DM953 = 2       5 << -1   桁数が負なら逆向き (Ruby と同じ)
#   $DM954 = 0       5 << 32   32 桁以上ずらすと左は 0
#   $DM955 = -1      -5 >> 32  右は符号で埋まる
#
# 実機でのみ意味を持つ検証。

a = 12
b = 10
$DM940 = a & b
$DM941 = a | b
$DM942 = a ^ b
$DM943 = ~5
$DM944 = a << 2
$DM945 = a >> 2
$DM946 = -5 >> 1

# ビットを立てて、見て、落とす
w = 0
w = w | 4
$DM947 = 0
if (w & 4) != 0
  $DM947 = 1
end
w = w & ~4
$DM948 = 0
if (w & 4) != 0
  $DM948 = 1
end

$DM950L = 1 << 16

# 端の扱い。桁数が負なら向きが逆、32 桁以上は振り切る
$DM952 = -5 << 1
$DM953 = 5 << -1
$DM954 = 5 << 32
$DM955 = -5 >> 32
