# 整数のビットを取る (Integer#[])
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# **PLC はビットを扱う場面が多いので、`(n >> i) & 1` と書かずに済ませます。**
# `n[i]` は OP_GETIDX になり、配列や文字列と同じ命令を通ります。
#
# Ruby と同じで、添字が負なら 0、桁数以上なら符号ビットです (上は無限に
# 符号が続いているものとして扱います)。
#
# 期待値:
#   $D140 = 1       5[0]  下位ビット
#   $D141 = 0       5[1]
#   $D142 = 1       5[2]
#   $D143 = 0       5[3]
#   $D144 = 1       添字を変数で渡す (n[m], m = 2)
#   $D145 = 0       5[31] 正の数の符号ビット
#   $D146 = 1       (-2)[31] 負の数の符号ビット
#   $D147 = 1       (-1)[40] 桁数を超えても符号が続く
#   $D148 = 0       5[-1] 負の添字は 0
#   $D149 = 1       デバイスから読んだ値のビット ($D130 = 6 の 1 ビット目)
#
# 実機でのみ意味を持つ検証。

n = 5
$D140 = n[0]
$D141 = n[1]
$D142 = n[2]
$D143 = n[3]

m = 2
$D144 = n[m]

$D145 = n[31]

p = -2
$D146 = p[31]

q = -1
$D147 = q[40]

$D148 = n[-1]

$D130 = 6
w = $D130
$D149 = w[1]
