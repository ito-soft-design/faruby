# プールの回収 (簡易 GC)
#
# 対象機種: iQ-R
#
# **キーエンス版からデバイス名だけを置き換えたものです** (`DM` → `D`)。
#
# **Q は入れていません。** 容量のために配列・文字列・ハッシュを外して
# いるので、このプログラムはコンパイル時に弾かれます (tools/features.rb)。
# Q でプールを使うのは `new` だけです。
#
# **使い捨ての値を作り続けてプールを使い切らせます。** 返さない案 2 では
# ここでエラー 10 で止まっていました。回収が入ったので止まらず、**生きて
# いるものは残っている**ことを見ます (doc/gc.md)。
#
# **実機でしか出ない形が 3 つあります。**
#
# 1. **回収は確保の 9 箇所に展開されています。** どこかの展開で Z の借用を
#    間に挟むと、呼ぶ側が載せていたアドレスが壊れます。ここは文字列・配列・
#    ハッシュ・オブジェクトの確保を全部通します
# 2. **要素数 0 の配列**を生かしたまま回収させます。伝播で「要素数 - 1」を
#    計算すると符号なしの 0 - 1 が 65535 になり、FOR が 65536 回回ります。
#    シミュレータは Ruby の整数なので -1 のまま空回りして**気づけません**
# 3. **プールが尽きた後は確保のたびに回収が走ります。** 50 回まわるので、
#    スキャンタイムの山が実機で問題にならないかもここで分かります
#
# 生きているものはルートから直接届くものだけではありません。配列の要素・
# ハッシュの値・オブジェクトのインスタンス変数・入れ子の内側は、プールの
# 中から指されています。**辿らないと回収され、エラーも出さずに値が
# 変わります。**
#
# 期待値:
#   $D1160 = 50      50 回まわりきった (止まっていない = 回収が走った)
#   $D1161 = 1       配列が持っている文字列が生き残る
#   $D1162 = 1       ハッシュの値が生き残る
#   $D1163 = 1       オブジェクトの @ が生き残る
#   $D1164 = 5       入れ子の内側が生き残る (2 + 3)
#   $D1165 = 0       要素数 0 の配列が壊れない
#   $D1166 = 3       配列の要素数が変わらない
#
# 実機でのみ意味を持つ検証。

class Holder
  def initialize(s)
    @s = s
  end

  def value
    @s
  end
end

# ここまでで 14 スロット使う (スロットは 32 個)
#   a + 要素 3 本 + empty + ハッシュ (文字列 2 + 配列 2) + obj の文字列と
#   オブジェクト + 入れ子 3
a = []
3.times do
  a << "ab"
end
empty = []
h = { x: "hx", y: "hy" }
o = Holder.new("obj")
nest = [[1, 2], [3, 4]]

# **ここでプールを使い切らせます。** 使い捨ては毎周どこからも届かなくなる
n = 0
50.times do
  t = "zz"
  n = n + 1
end

$D1160 = n

$D1161 = 0
if a[0] == "ab"
  if a[2] == "ab"
    $D1161 = 1
  end
end

$D1162 = 0
if h[:x] == "hx"
  if h[:y] == "hy"
    $D1162 = 1
  end
end

$D1163 = 0
if o.value == "obj"
  $D1163 = 1
end

$D1164 = nest[0][1] + nest[1][0]
$D1165 = empty.length
$D1166 = a.length
