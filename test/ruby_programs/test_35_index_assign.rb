# 添字への複合代入 (x[i] op= v)
#
# 対象機種: KV-5000, KV-X500
#
# **ラダーの `DM0.0` に当たるものです。** インデックス修飾ではビットを指定
# できないので、読んで直して書きます。
#
#   $DM[a] |= 1 << 3     ビットを立てる
#   $DM[a] &= ~(1 << 3)  落とす
#   $DM[a][3]            読む
#
# `x[i] op= v` は `[]` と `[]=` のメソッド呼び出しになります。素の `x[i]` が
# OP_GETIDX なのに複合代入だけ呼び出しになるのは mruby の出し方で、
# ホスト側で専用命令に置き換えています。配列とハッシュにも同じ穴が空いて
# いたので、まとめて塞がりました。
#
# 期待値:
#   $DM150 = 9       $DM[i] = 1 にビット 3 を立てる
#   $DM151 = 14      $DM[i] = 15 からビット 0 を落とす
#   $DM152 = 1       立てたビットを添字で読む
#   $DM153 = 15      配列の要素を足す (a[0] += 5)
#   $DM154 = 3       ハッシュの値を足す (h["n"] += 2)
#   $DM155 = 22      引数 2 個の [] は連続読みのまま
#
# 実機でのみ意味を持つ検証。

i = 150
$DM[i] = 1
$DM[i] |= 1 << 3

$DM151 = 15
j = 151
$DM[j] &= ~(1 << 0)

$DM152 = 0
$DM152 = 1 if $DM[i][3] == 1

a = [10, 20]
a[0] += 5
$DM153 = a[0]

h = { "n" => 1 }
h["n"] += 2
$DM154 = h["n"]

$DM160 = 11
$DM161 = 22
b = $DM[160, 2]
$DM155 = b[1]
