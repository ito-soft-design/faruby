# 配列の生成と添字アクセス
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# 実体は固定数のスロットを並べた配列プールに置き、レジスタには型タグと
# スロット番号だけが入る。スロットは順に渡して返さないため、ループの中で
# 作り続けるといずれ「配列の領域が足りない」で止まる。
#
# 添字の読みは範囲外でも nil (Ruby と同じ)。書きは要素数を超えると配列を
# 伸ばし、間を nil で埋める。ただし容量は固定なので超えるとエラーになる。
#
# 期待値:
#   $D710 = 22     a[1]
#   $D711 = 11     a[0]
#   $D712 = 33     a[-1] は最後の要素
#   $D713 = 1      範囲外の読みは nil
#   $D714 = 99     a[0] = 99
#   $D715 = 99     要素数を超える位置へ代入すると伸びる
#   $D716 = 1      伸ばした隙間は nil
#   $D717 = 3      入れ子 a[1][0]
#   $D718 = 6      ループで読む
#   $D719 = 3      ループで書く
#   $D720 = 8      メソッドから返した配列
#   $D721 = 42     デバイスの値を要素にする
#   $D722 = 3      length
#   $D723 = 3      size
#   $D724 = 0      空配列の length
#   $D725 = 5      << で足す
#   $D726 = 2      << を重ねる
#   $D727 = 9      push
#   $D728 = 5      ループで詰める
#   $D729 = 12     詰めてから合計する
#   $D731 = 66     each は要素を渡す (添字なら 0+1+2 = 3 になる)
#
# 実機でのみ意味を持つ検証。
#
# プールは 16 スロットしかないため、配列を新しく作る行を増やすと
# 「配列の領域が足りない」で止まります。既存の配列を使い回してください。

a = [11, 22, 33]
$D710 = a[1]
$D711 = a[0]
$D712 = a[-1]

$D713 = 0
if a[5] == nil
  $D713 = 1
end

b = [11, 22]
b[0] = 99
$D714 = b[0]

c = [11]
c[2] = 99
$D715 = c[2]
$D716 = 0
if c[1] == nil
  $D716 = 1
end

d = [[1, 2], [3, 4]]
$D717 = d[1][0]

e = [1, 2, 3]
s = 0
3.times do |i|
  s = s + e[i]
end
$D718 = s

f = [0, 0, 0]
3.times do |i|
  f[i] = i + 1
end
$D719 = f[2]

def make
  [7, 8]
end
g = make
$D720 = g[1]

$D730 = 42
h = [$D730]
$D721 = h[0]

# プールは 16 スロットしかないため、新しく作らず既存の配列を使い回す
$D722 = a.length
$D723 = a.size

j = []
$D724 = j.length
j << 5
$D725 = j[0]
j << 6
$D726 = j.length

m = [1]
m.push(9)
$D727 = m[1]

n = []
5.times do |x|
  n << x
end
$D728 = n.length

p = []
4.times do |x|
  p << x * 2
end
t = 0
4.times do |x|
  t = t + p[x]
end
$D729 = t

# each はブロックに添字ではなく要素を渡す。
# 添字が渡っていれば 0+1+2 = 3 になるので取り違えを検出できる
t = 0
a.each do |v|
  t = t + v
end
$D731 = t
