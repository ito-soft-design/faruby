# 文字列の比較と連結
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# **`==` は中身で比べる。** レジスタに入っているのはスロット番号なので、
# 同じ内容が別のスロットにあると番号では等しくならない。バイト数が同じなら
# ワード単位で比べる (並びが揃っているので回数はバイト数の半分)。
#
# ハッシュの鍵も同じ判定にする。文字列の鍵はスロットが違っても同じ鍵。
#
# 連結は 2 つ。`+` は新しいスロットを取り、`OP_STRCAT` (式展開) は
# 継ぎ足す先をそのまま伸ばす。継ぎ足す先の長さが奇数だとワードの途中から
# 始まるので、そこはバイト単位で書く。
#
# 期待値:
#   $D3960 = 1       別のスロットの同じ内容は等しい
#   $D3961 = 1       長さが違えば等しくない
#   $D3962 = 7       文字列の鍵で引ける
#   $D3963 = 9       新しい文字列の鍵を足せる
#   $D3970U = 24930  "ab"   a + b
#   $D3971U = 25444  "cd"
#   $D3972U = 0      終端
#   $D3974U = 28792  "px"   式展開 "p#{c}q"
#   $D3975U = 28928  "q\0"
#   $D3978U = 24930  "ab"   + は左側を変えない
#   $D3979U = 0      終端
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと `+` の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

FARUBY_STR_FILL = 0x20

s = "hello"
t = "hello"

$D3960 = 0
if s == t
  $D3960 = 1
end

$D3961 = 0
if s != "hell"
  $D3961 = 1
end

# 文字列の鍵。書いたときと引くときで別のスロットになる
h = { "x" => 7 }
$D3962 = h["x"]
h["z"] = 9
$D3963 = h["z"]

a = "ab"
b = "cd"
$D3970 = a + b

c = "x"
$D3974 = "p#{c}q"

# + は新しいスロットを取るので、左側は変わらない
$D3978 = a
