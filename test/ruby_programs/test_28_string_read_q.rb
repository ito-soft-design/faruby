# デバイスから文字列を読む
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# **桁数がそのままバイト数。何も落とさない。** 表示器の桁が空白で埋まって
# いれば、その空白も中身に入る。落とす規則を持つと、末尾の空白が意味を持つ
# データを扱えなくなる。比べたい桁に合わせて書く。
#
# 桁の無い `T` は読めない。書くときは終端付きの意味だが、読むときは
# 長さが決まらないため。エラー 21。
#
# 添字を付けた形 (`$DMT6[i]`) も同じ経路を通る。表示器の桁が並んでいる
# ところから 1 つずつ読める。
#
# 期待値:
#   $D3940 = 6       読み戻した長さ
#   $D3941 = 1       同じ中身なら等しい
#   $D3942 = 3       奇数の桁も読める
#   $D3943 = 1       桁の外のバイトは混ざらない
#   $D3944 = 2       "あい" は 6 バイトで 2 文字
#   $D3945 = 1       添字を付けた形も読める
#   $D3960U = 16706  読んだものを書き戻すと同じ並び
#   $D3961U = 17220
#   $D3962U = 17734
#   $D3963U = 0
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと読み取りがそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

$D3100T6 = "ABCDEF"
s = $D3100T6
$D3940 = s.length

$D3941 = 0
if s == "ABCDEF"
  $D3941 = 1
end

# 奇数の桁。最後のワードの下位バイトは桁の外
$D3110T3 = "xyz"
t = $D3110T3
$D3942 = t.length
$D3943 = 0
if t == "xyz"
  $D3943 = 1
end

# UTF-8 は 1 文字 3 バイト。桁はバイト数で数える
$D3120T6 = "あい"
u = $D3120T6
$D3944 = u.length

# 添字を付けた形。桁は名前側に付ける ($DMT6)
i = 0
v = $DMT6[100 + i]
$D3945 = 0
if v == "ABCDEF"
  $D3945 = 1
end

$D3960 = s
