# ハッシュのメソッド
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# size / length は組の数。鍵の配列の見出しから読む。
# key? は鍵の配列の線形走査で、一致は型と値の両方。
# keys / values は Ruby と同じく新しい配列を返すため、**プールを 1 スロット
# 使う**。ループの中で呼び続けると使い切る。配列リテラルと同じ制約。
#
# 期待値:
#   $D3760 = 3      size
#   $D3761 = 3      length
#   $D3762 = 0      空ハッシュの size
#   $D3763 = 1      key? が真
#   $D3764 = 1      key? が偽
#   $D3765 = 3      keys の要素数
#   $D3766 = 1      values[0]
#   $D3767 = 3      values[2]
#   $D3768 = 1      整数の鍵 keys[0]
#   $D3769 = 2      整数の鍵 keys[1]
#   $D3770 = 3      keys は新しい配列なので足せる
#   $D3771 = 2      足してもハッシュは変わらない
#   $D3772 = 4      鍵を足した後の size
#   $D3773 = 1      足した鍵の key?
#   $D3774 = 4      足した後の values の最後
#   $D3775 = 0      空ハッシュの keys
#   $D3776 = 4      ブロックの中から size
#
# 実機でのみ意味を持つ検証。
#
# プールは 16 スロットで、ハッシュ 1 つが 2 つ、keys / values が 1 つずつ
# 使います。行を増やすときは残りに気をつけてください。

h = { a: 1, b: 2, c: 3 }
$D3760 = h.size
$D3761 = h.length

e = {}
$D3762 = e.size

$D3763 = 0
if h.key?(:b)
  $D3763 = 1
end

$D3764 = 0
if !h.key?(:z)
  $D3764 = 1
end

k = h.keys
$D3765 = k.length

v = h.values
$D3766 = v[0]
$D3767 = v[2]

g = { 1 => 10, 2 => 20 }
gk = g.keys
$D3768 = gk[0]
$D3769 = gk[1]

# keys が返すのは新しい配列。足してもハッシュ側は変わらない
gk << 99
$D3770 = gk.length
$D3771 = g.size

h[:d] = 4
$D3772 = h.size
$D3773 = 0
if h.key?(:d)
  $D3773 = 1
end
hv = h.values
$D3774 = hv[3]

ek = e.keys
$D3775 = ek.length

2.times do
  $D3776 = h.size
end
