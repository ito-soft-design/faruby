# 文字列のメソッド
#
# **`length` は文字数を返す。** `"あ".length` は Ruby では 1 で、バイト数の
# 3 ではない。バイト列を先頭から 1 回なめて切れ目を数える。同じ走査で
# `s[i]` のバイト位置も出るので、両方を同じ手順で済ませている。
#
# `empty?` は長さが 0 かどうかだけなので、切れ目は数えない。
#
# `<<` は文字列なら中身を継ぎ足し、配列なら末尾に足す。どちらも Ruby は
# レシーバ自身を返す。`push` は配列だけ (Ruby の String に push は無い)。
#
# `s[i]` は **1 文字の文字列**を返す。プールを 1 スロット使うので、
# ループの中で呼び続けると使い切る。
#
# 期待値:
#   $DM940 = 5       "hello".length
#   $DM941 = 5       size も同じ
#   $DM942 = 2       "あい".length は文字数。バイト数の 6 ではない
#   $DM944 = 1       "".empty?
#   $DM945 = 0       "a".empty? は偽
#   $DM946 = 1       [].empty?
#   $DM947 = 0       { 1 => 2 }.empty? は偽
#   $DM948 = 4       文字列の << で伸びた長さ
#   $DM949 = 3       配列の << は今までどおり
#   $DM960U = 24832  s[0] は "a"。終端付きなので下位バイトは 0
#   $DM962U = 25600  s[-1] は "d"。負の添字は後ろから数える
#   $DM964U = 0      s[9] は範囲外で nil
#   $DM966U = 58241  "あい"[1] は 3 バイトの "い"
#   $DM967U = 33792
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと s[i] の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

h = "hello"
$DM940 = h.length
$DM941 = h.size

j = "あい"
$DM942 = j.length

$DM944 = 0
if "".empty?
  $DM944 = 1
end

$DM945 = 0
if "a".empty?
  $DM945 = 1
end

$DM946 = 0
if [].empty?
  $DM946 = 1
end

k = { 1 => 2 }
$DM947 = 0
if k.empty?
  $DM947 = 1
end

s = "abc"
s << "d"
$DM948 = s.length

a = [1, 2]
a << 3
$DM949 = a.length

$DM960 = s[0]
$DM962 = s[-1]
$DM964 = s[9]
$DM966 = j[1]
