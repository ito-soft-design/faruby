# 配列とデバイスの間で写す
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# `$D3100 = a` で a の要素を DM100 から順に書く。**刻みは幅で決まる。**
# `.S` / `.U` は 1 ワード、`.L` / `.D` / `.F` は 2 ワードずつ進む。
#
# ビットデバイスは 1 ワードが 16 ビットにあたるので、`$ML[64] = a` は
# 64・96・128 ビット目へ書く。**個別ビット (幅なし) には書けない。**
# 1 要素が何ビットか決まらないため。
#
# 要素は数値だけ。中に文字列や配列があると止まる。ハッシュも書けない。
#
# 期待値:
#   $D3940 = 11      16 ビット。3 要素が並ぶ
#   $D3941 = 22
#   $D3942 = 33
#   $D3944L = 100    32 ビットは 2 ワードずつ
#   $D3946L = 200
#   $D3950F = 1.5    実数も書ける
#   $D3952F = 2.5
#   $D3954 = 7       添字を付けた形も同じ
#   $D3955 = 8
#   $D3960L = 5      ビットデバイスは 16 ビット刻み。書いて読み戻す
#   $D3962L = 6
#   $D3964 = 3       $D[940, 3] で 3 個読む
#   $D3965 = 11      その 0 番目
#   $D3966 = 33      その 2 番目
#   $D3967 = 100     32 ビットも同じ
#   $D3968 = 1       個数が負なら nil (Ruby と同じ)
#
# 実機でのみ意味を持つ検証。

a = [11, 22, 33]
$D3940 = a

b = [100, 200]
$D3944L = b

c = [1.5, 2.5]
$D3950F = c

i = 0
$D[954 + i] = [7, 8]

# ビットデバイス。幅を付けたときだけ書ける
$ML[64 + i] = [5, 6]
$D3960L = $ML[64]
$D3962L = $ML[96]

# デバイスから配列へ。個数を書く
d = $D[940, 3]
$D3964 = d.length
$D3965 = d[0]
$D3966 = d[2]

e = $DML[944, 2]
$D3967 = e[0]

f = $D[940, -1]
$D3968 = 0
if f == nil
  $D3968 = 1
end
