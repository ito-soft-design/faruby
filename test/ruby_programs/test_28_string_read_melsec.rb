# デバイスから文字列を読む
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# **桁数がそのままバイト数。何も落とさない。** 表示器の桁が空白で埋まって
# いれば、その空白も中身に入る。落とす規則を持つと、末尾の空白が意味を持つ
# データを扱えなくなる。比べたい桁に合わせて書く。
#
# 桁の無い `T` は読めない。書くときは終端付きの意味だが、読むときは
# 長さが決まらないため。エラー 21。
#
# 添字を付けた形 (`$DT6[i]`) も同じ経路を通る。表示器の桁が並んでいる
# ところから 1 つずつ読める。
#
# 期待値:
#   $D940 = 6       読み戻した長さ
#   $D941 = 1       同じ中身なら等しい
#   $D942 = 3       奇数の桁も読める
#   $D943 = 1       桁の外のバイトは混ざらない
#   $D944 = 2       "あい" は 6 バイトで 2 文字
#   $D945 = 1       添字を付けた形も読める
#   $D960U = 16706  読んだものを書き戻すと同じ並び
#   $D961U = 17220
#   $D962U = 17734
#   $D963U = 0
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと読み取りがそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

$D100T6 = "ABCDEF"
s = $D100T6
$D940 = s.length

$D941 = 0
if s == "ABCDEF"
  $D941 = 1
end

# 奇数の桁。最後のワードの下位バイトは桁の外
$D110T3 = "xyz"
t = $D110T3
$D942 = t.length
$D943 = 0
if t == "xyz"
  $D943 = 1
end

# UTF-8 は 1 文字 3 バイト。桁はバイト数で数える
$D120T6 = "あい"
u = $D120T6
$D944 = u.length

# 添字を付けた形。桁は名前側に付ける ($DT6)
i = 0
v = $DT6[100 + i]
$D945 = 0
if v == "ABCDEF"
  $D945 = 1
end

$D960 = s
