# デバイスの割り付け
#
# 対象機種: KV-5000, KV-X500
#
# devices: test_40_device_map.devices.rb
#
# 抽象的な名前を実デバイスに割り付け、設備が変わってもプログラムを直さずに
# 済むようにするものです。**実行時の費用はゼロ**で、実デバイスを直に書いたのと
# 同じバイトコードになります (種別と番号は実行時にシンボル表から引くので、
# 表の項目に割り付け先を入れるだけで済む)。
#
# **実機で確かめたいのはそこです。** ホスト側だけの仕組みなので生成物は
# 変わりませんが、シンボル表に正しい種別と番号が入っていなければ別のデバイスを
# 指します。ビット・ワード・幅付き・生成した項目・実デバイスとの混在を
# それぞれ通します。
#
# 期待値:
#   $motor = 1        割り付けたビットデバイス (MR101)
#   $count = 7        割り付けたワードデバイス (DM1040)
#   $speed = 100000   割り付け先に幅が付いている (DM1041L の 2 ワード)
#   $DM1043 = 6       繰り返しで生成した割り付け (in_0..in_3 の和)
#   $DM1044 = 42      割り付けた名前と実デバイスは混ぜて書ける
#
# 実機でのみ意味を持つ検証。

$motor = true
$count = 7
$speed = 100000

$in_0 = 0
$in_1 = 1
$in_2 = 2
$in_3 = 3
$DM1043 = $in_0 + $in_1 + $in_2 + $in_3

$DM1044 = 42
