# ビットデバイスの読み書き
#
# 対象機種: Q, iQ-R
#
# **キーエンス版の写しではありません。** 種別が違います。キーエンスの `R` は
# ビットデバイスですが、三菱の `R` はワードデバイス (ファイルレジスタ) です。
# 三菱のビットデバイスは M (内部リレー) / L (ラッチリレー) / B (リンクリレー) /
# X (入力) / Y (出力) です。
#
# **書き込みは TRUE / FALSE の代入です。** 整数を書くと非 0 が ON になり、
# 読むと真偽値になります (整数の 0 は Ruby では真なので、整数のままだと
# `if $M10` が常に成立してしまいます)。
#
# **X は入力なので書きません。** リフレッシュで上書きされます。
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 期待値:
#   $D3120 = 1       $M10 = 1 (非0) → ON
#   $D3121 = 1       $M11 = true → ON
#   $D3122 = 1       $M200 = 43 (非0) → ON
#   $D3123 = 1       $L300 = true → ON
#   $D3124 = 0       $B400 = false → OFF
#   $D3125 = 0       $Y10 = 0 → OFF
#
# 実機でのみ意味を持つ検証。

$M10 = false
$M11 = false
$M200 = false
$L300 = false
$B400 = true
$Y10 = true

$D3100 = 42
$M10 = 1
$M11 = true
$M200 = $D3100 + $M10
$L300 = true
$B400 = false
$Y10 = 0

$D3120 = 0
$D3120 = 1 if $M10
$D3121 = 0
$D3121 = 1 if $M11
$D3122 = 0
$D3122 = 1 if $M200
$D3123 = 0
$D3123 = 1 if $L300
$D3124 = 0
$D3124 = 1 if $B400
$D3125 = 0
$D3125 = 1 if $Y10
