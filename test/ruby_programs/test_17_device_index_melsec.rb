# 添字によるデバイスアクセス
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# デバイスアドレスをコンパイル時ではなく実行時に決める。
# 裸の $D がデバイス族を表し、添字を付けると実際の読み書きになる。
#
# 添字は「デバイス番号」です。ワードデバイスは表示上のアドレスと一致しますが、
# MR / R / B は一致しません (MR400 は番号 64)。番号空間では線形なので、
# MR415 の次は MR500 になります。
#
# 期待値:
#   $D600-$D604      = 0, 10, 20, 30, 40   ループで書き込み
#   $D610             = 100                 合計 (ループで読み出し)
#   $D612L (32ビット) = 70000                幅サフィックス付き
#   MR400, MR402       = ON                  ビットデバイス (番号 64, 66)
#   MR401              = OFF
#
# 実機でのみ意味を持つ検証。

# ループで書き込む
i = 0
while i < 5
  $D[600 + i] = i * 10
  i = i + 1
end

# ループで読み出して合計する
sum = 0
i = 0
while i < 5
  sum = sum + $D[600 + i]
  i = i + 1
end
$D610 = sum

# 32ビット幅で書き込む
$DL[612] = 70000

# ビットデバイス。64 は MR400 の番号
# (!= はメソッド呼び出しになるため if で書く)
b = 0
while b < 3
  if b == 1
    $M[64 + b] = false
  else
    $M[64 + b] = true
  end
  b = b + 1
end
