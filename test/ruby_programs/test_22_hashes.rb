# ハッシュの生成と添字アクセス
#
# 実体は配列プールのスロット 2 つ (鍵の配列と値の配列)。レジスタには型タグと
# スロット番号 2 つが入る。検索は鍵の配列の線形走査で、一致は型と値の両方。
#
# 無い鍵は nil、既にある鍵は値だけ差し替え、新しい鍵は両方の末尾に足す。
#
# 期待値:
#   $DM740 = 2      h[:b]
#   $DM741 = 1      h[:a]
#   $DM742 = 1      無い鍵は nil
#   $DM743 = 3      新しい鍵は足される
#   $DM744 = 9      既にある鍵は差し替わる
#   $DM745 = 2      差し替えても他の鍵は変わらない
#   $DM746 = 1      3 組の 1 つ目 (オペランドが組の数であることの確認)
#   $DM747 = 2      3 組の 2 つ目
#   $DM748 = 3      3 組の 3 つ目
#   $DM749 = 10     整数の鍵
#   $DM750 = 20     整数の鍵
#   $DM751 = 1      空ハッシュはどの鍵も nil
#   $DM752 = 5      空ハッシュに足せる
#   $DM753 = 8      メソッドが返したハッシュ
#   $DM754 = 8      値が配列
#   $DM755 = 20     ループで詰める
#   $DM756 = 9      ブロックの中から引く (シンボルが irep をまたぐ)
#
# 実機でのみ意味を持つ検証。
#
# ハッシュ 1 つがプールを 2 スロット使うため、全 16 スロットでは
# ハッシュ 8 個が限度です。新しく作らず既存のものを使い回してください。

a = { a: 1, b: 2 }
$DM740 = a[:b]
$DM741 = a[:a]

$DM742 = 0
if a[:zz] == nil
  $DM742 = 1
end

a[:c] = 3
$DM743 = a[:c]

a[:a] = 9
$DM744 = a[:a]
$DM745 = a[:b]

# 組が 3 つ。OP_HASH のオペランドがレジスタ数ではなく組の数であること
b = { x: 1, y: 2, z: 3 }
$DM746 = b[:x]
$DM747 = b[:y]
$DM748 = b[:z]

c = { 1 => 10, 2 => 20 }
$DM749 = c[1]
$DM750 = c[2]

d = {}
$DM751 = 0
if d[:a] == nil
  $DM751 = 1
end
d[:a] = 5
$DM752 = d[:a]

def make
  { k: 8 }
end
e = make
$DM753 = e[:k]

f = { v: [7, 8] }
$DM754 = f[:v][1]

# 新しく作らず d を使い回す。整数の鍵はシンボルの :a と型が違うのでぶつからない
3.times do |i|
  d[i] = i * 10
end
$DM755 = d[2]

# ブロックの中の :a はトップレベルの :a と別の irep にある
2.times do
  $DM756 = a[:a]
end
