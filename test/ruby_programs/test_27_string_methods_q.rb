# 文字列のメソッド
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# **`length` は文字数を返す。** `"あ".length` は Ruby では 1 で、バイト数の
# 3 ではない。バイト列を先頭から 1 回なめて切れ目を数える。同じ走査で
# `s[i]` のバイト位置も出るので、両方を同じ手順で済ませている。
#
# `empty?` は長さが 0 かどうかだけなので、切れ目は数えない。
#
# `<<` は文字列なら中身を継ぎ足し、配列なら末尾に足す。どちらも Ruby は
# レシーバ自身を返す。`push` は配列だけ (Ruby の String に push は無い)。
#
# `s[i]` は **1 文字の文字列**を返す。プールを 1 スロット使うので、
# ループの中で呼び続けると使い切る。
#
# 期待値:
#   $D3940 = 5       "hello".length
#   $D3941 = 5       size も同じ
#   $D3942 = 2       "あい".length は文字数。バイト数の 6 ではない
#   $D3944 = 1       "".empty?
#   $D3945 = 0       "a".empty? は偽
#   $D3946 = 1       [].empty?
#   $D3947 = 0       { 1 => 2 }.empty? は偽
#   $D3948 = 4       文字列の << で伸びた長さ
#   $D3949 = 3       配列の << は今までどおり
#   $D3960U = 24832  s[0] は "a"。終端付きなので下位バイトは 0
#   $D3962U = 25600  s[-1] は "d"。負の添字は後ろから数える
#   $D3964U = 0      s[9] は範囲外で nil
#   $D3966U = 58241  "あい"[1] は 3 バイトの "い"
#   $D3967U = 33792
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと s[i] の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

h = "hello"
$D3940 = h.length
$D3941 = h.size

j = "あい"
$D3942 = j.length

$D3944 = 0
if "".empty?
  $D3944 = 1
end

$D3945 = 0
if "a".empty?
  $D3945 = 1
end

$D3946 = 0
if [].empty?
  $D3946 = 1
end

k = { 1 => 2 }
$D3947 = 0
if k.empty?
  $D3947 = 1
end

s = "abc"
s << "d"
$D3948 = s.length

a = [1, 2]
a << 3
$D3949 = a.length

$D3960 = s[0]
$D3962 = s[-1]
$D3964 = s[9]
$D3966 = j[1]
