# ワードデバイスのアクセス幅サフィックス
#
# 対象機種: Q
#
# **三菱に幅のサフィックスはありません。** 32 ビットは 16 ビット 2 回に開いて
# スクラッチの重ね合わせに載せ、符号なしは負なら 65536 を足して広げます
# (doc/melsec.md)。faRuby 側で吸収するので、Ruby の書き方はキーエンスと同じです。
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 期待値:
#   $D3300  = -100    (16bit符号付き、D3300 の1ワードのみ)
#   $D3310L = 100000  (32bit符号付き、D3310/D3311 の2ワード)
#   $D3320U = 60000   (16bit符号なし、D3320 の1ワードのみ)

$D3300 = -100
$D3310L = 100000
$D3320U = 60000
$M10 = 1
