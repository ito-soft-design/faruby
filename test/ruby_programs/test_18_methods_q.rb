# 組み込みメソッド
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# OP_SEND の限定実装。呼び出しフレームを作らず、その場で計算して返す。
# メソッド名はホスト側で番号に解決済みで、VM は整数の分岐で振り分ける。
#
# 期待値:
#   $D3620 = 1     1 != 2
#   $D3621 = 0     1 != 1.0        数値は型が違っても値で比べる
#   $D3622 = 1     nil != false    型が違えば等しくない
#   $D3623 = 1     !nil
#   $D3624 = 0     !0              Ruby では 0 も真
#   $D3625 = 1     7 % 3
#   $D3626 = 2     -7 % 3          符号は除数に合う
#   $D3627 = -2    7 % -3
#   $D3628 = 3     (-3).abs
#   $D3629 = -2    (-2.7).to_i     0 方向へ切り捨て
#   $D3630 = -3    (-2.7).floor    -∞ 方向
#   $D3631 = 3     2.5.round       0 から遠い方へ
#   $D3632 = -3    (-2.5).round
#   $D3634F = 2.5  (-2.5).abs      実数は型が変わらない
#   $D3636F = 3.0  3.to_f
#
# 32ビットで読む必要はない ($D3620 等は16ビット符号付き)。
# $D3634F と $D3636F は 2 ワードずつ占有する。
#
# 実機でのみ意味を持つ検証。

a = 1
b = 2
c = 1.0

$D3620 = 0
if a != b
  $D3620 = 1
end

$D3621 = 0
if a != c
  $D3621 = 1
end

n = nil
f = false
$D3622 = 0
if n != f
  $D3622 = 1
end

$D3623 = 0
if !n
  $D3623 = 1
end

z = 0
$D3624 = 0
if !z
  $D3624 = 1
end

# 剰余。定数どうしは mrbc が畳み込むため変数を挟む
p = 7
q = 3
$D3625 = p % q

p = -7
$D3626 = p % q

p = 7
q = -3
$D3627 = p % q

# 数値変換
v = -3
$D3628 = v.abs

w = -2.7
$D3629 = w.to_i
$D3630 = w.floor

r = 2.5
$D3631 = r.round

r = -2.5
$D3632 = r.round
$D3634F = r.abs

t = 3
$D3636F = t.to_f
