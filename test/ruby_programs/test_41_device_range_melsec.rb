# 割り付けた範囲を添字で引く
#
# 対象機種: Q, iQ-R
#
# devices: test_41_device_range_melsec.devices.rb
#
# **キーエンス版と本文がまったく同じです。** 違うのは割り付け表だけです。
#
# **ビットデバイスの番号の数え方だけは結果が変わります。** キーエンスの `MR` は
# チャンネルとビットに分かれているので `$bits[6]` が `MR200` になりますが、
# 三菱の `M` は 10 進そのままなので `M116` です。**数え方は割り付け表の側が
# 知っていて、プログラムは知りません。**
#
# 期待値:
#   $D1100  = 0        $regs[0]
#   $D1107  = 70       $regs[7] (範囲の端)
#   $D1120  = 30       $regs[3] を読み直した値
#   $D1110L = 100000   $pair[0] (32 ビット)
#   $D1112L = 200000   $pair[2] (ワードで 2 つ先)
#   $M110   = 1        $bits[0]
#   $M115   = 1        $bits[5]
#   $M116   = 1        $bits[6] (10 進そのまま)
#
# 実機でのみ意味を持つ検証。

8.times { |i| $regs[i] = i * 10 }
$D1120 = $regs[3]

$pair[0] = 100000
$pair[2] = 200000

$bits[0] = true
$bits[5] = true
$bits[6] = true
