# 添字によるデバイスアクセス
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# デバイスアドレスをコンパイル時ではなく実行時に決める。
# 裸の $DM がデバイス族を表し、添字を付けると実際の読み書きになる。
#
# 添字は「デバイス番号」です。ワードデバイスは表示上のアドレスと一致しますが、
# **三菱のビットデバイスは 10 進**なので、表示上のアドレスがそのまま番号
# です。キーエンスの MR / R / B は一致しません (MR400 は番号 64)。
#
# 期待値:
#   $D3600-$D3604      = 0, 10, 20, 30, 40   ループで書き込み
#   $D3610             = 100                 合計 (ループで読み出し)
#   $D3612L (32ビット) = 70000                幅サフィックス付き
#   M64, M66           = ON                  ビットデバイス
#   M65                = OFF
#
# 実機でのみ意味を持つ検証。

# ループで書き込む
i = 0
while i < 5
  $D[600 + i] = i * 10
  i = i + 1
end

# ループで読み出して合計する
sum = 0
i = 0
while i < 5
  sum = sum + $D[600 + i]
  i = i + 1
end
$D3610 = sum

# 32ビット幅で書き込む
$DML[612] = 70000

# ビットデバイス。三菱は表示アドレスがそのまま番号
# (!= はメソッド呼び出しになるため if で書く)
b = 0
while b < 3
  if b == 1
    $M[64 + b] = false
  else
    $M[64 + b] = true
  end
  b = b + 1
end
