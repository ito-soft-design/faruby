# 組み込みメソッド
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# OP_SEND の限定実装。呼び出しフレームを作らず、その場で計算して返す。
# メソッド名はホスト側で番号に解決済みで、VM は整数の分岐で振り分ける。
#
# 期待値:
#   $D620 = 1     1 != 2
#   $D621 = 0     1 != 1.0        数値は型が違っても値で比べる
#   $D622 = 1     nil != false    型が違えば等しくない
#   $D623 = 1     !nil
#   $D624 = 0     !0              Ruby では 0 も真
#   $D625 = 1     7 % 3
#   $D626 = 2     -7 % 3          符号は除数に合う
#   $D627 = -2    7 % -3
#   $D628 = 3     (-3).abs
#   $D629 = -2    (-2.7).to_i     0 方向へ切り捨て
#   $D630 = -3    (-2.7).floor    -∞ 方向
#   $D631 = 3     2.5.round       0 から遠い方へ
#   $D632 = -3    (-2.5).round
#   $D634F = 2.5  (-2.5).abs      実数は型が変わらない
#   $D636F = 3.0  3.to_f
#
# 32ビットで読む必要はない ($D620 等は16ビット符号付き)。
# $D634F と $D636F は 2 ワードずつ占有する。
#
# 実機でのみ意味を持つ検証。

a = 1
b = 2
c = 1.0

$D620 = 0
if a != b
  $D620 = 1
end

$D621 = 0
if a != c
  $D621 = 1
end

n = nil
f = false
$D622 = 0
if n != f
  $D622 = 1
end

$D623 = 0
if !n
  $D623 = 1
end

z = 0
$D624 = 0
if !z
  $D624 = 1
end

# 剰余。定数どうしは mrbc が畳み込むため変数を挟む
p = 7
q = 3
$D625 = p % q

p = -7
$D626 = p % q

p = 7
q = -3
$D627 = p % q

# 数値変換
v = -3
$D628 = v.abs

w = -2.7
$D629 = w.to_i
$D630 = w.floor

r = 2.5
$D631 = r.round

r = -2.5
$D632 = r.round
$D634F = r.abs

t = 3
$D636F = t.to_f
