# 単項の符号と括弧
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`)。
#
# **mruby は `-x` を `x.-@()` にします。** リテラルは定数畳み込みで消えるので、
# `-1` は届きません。変数や式に付けたときだけメソッド呼び出しになります。
# `+x` も同じく `+@` になり、Ruby と同じく何もしません。
#
# 括弧そのものは faRuby に届きません。mruby が順序を決めてバイトコードに
# するので、ここで見ているのは**順序が正しく実行されるか**です。
#
# 期待値:
#   $D990 = 14      a + b * c        掛け算が先
#   $D991 = 20      (a + b) * c      括弧が先
#   $D992 = 13      a * (b + c) - 1
#   $D993 = 5       ((a+b) * (c-1)) / 3
#   $D994 = 1       -(a - b)         式に付けた単項マイナス
#   $D995 = -2      -a               変数に付けた単項マイナス
#   $D996 = 2       +a               単項プラスは何もしない
#   $D997 = -1      -x.abs           メソッドの結果に付ける
#   $D1000L = -25   -(5 * 5)         32ビット (DM1000-DM1001)
#   $D1002F = -2.5  -y               実数 (DM1002-DM1003)
#
# **幅のあるものは離して置きます。** `$D998L` と `$D999F` は 1 ワード
# 重なり、後に書いた方が相手の上位ワードを潰します。
#
# 実機でのみ意味を持つ検証。

a = 2
b = 3
c = 4

$D990 = a + b * c
$D991 = (a + b) * c
$D992 = a * (b + c) - 1
$D993 = ((a + b) * (c - 1)) / 3

$D994 = -(a - b)
$D995 = -a
$D996 = +a

x = -1
$D997 = -x.abs
$D1000L = -(5 * 5)

y = 2.5
$D1002F = -y
