# 汎用グローバル変数はどの型でも持てる
#
# `$foo` のようにデバイス名でないグローバル変数は、汎用グローバル領域の
# **値スロット (4 ワード)** に置く。型タグごと写すので、実数も配列も
# ハッシュも文字列も `true` / `false` / `nil` もそのまま持てる。
#
# 以前は値ワードだけを 32 ビットで読み書きしていたため、実数は切り捨てられ、
# `false` と `nil` は整数 0 になって**真**になっていた。配列や文字列は
# スロット番号が整数として残り、使うとエラーで止まった。
#
# 配列や文字列を入れてもプールは増えない。入るのはスロット番号だけ。
#
# 期待値:
#   $DM940 = 1       実数がそのまま
#   $DM941 = 3       配列の length が引ける
#   $DM942 = 2       ハッシュが引ける
#   $DM943 = 0       false は偽
#   $DM944 = 0       nil は偽
#   $DM945 = 1       true は真
#   $DM946 = 3       文字列の length が引ける
#   $DM960U = 24930  文字列をデバイスへ書ける "ab"
#   $DM961U = 25344  "c" と終端
#
# 実機でのみ意味を持つ検証。

$g = 2.5
$DM940 = 0
if $g == 2.5
  $DM940 = 1
end

$g = [1, 2, 3]
$DM941 = $g.length

$g = { 1 => 2 }
$DM942 = $g[1]

$g = false
$DM943 = 0
if $g
  $DM943 = 1
end

$g = nil
$DM944 = 0
if $g
  $DM944 = 1
end

$g = true
$DM945 = 0
if $g
  $DM945 = 1
end

$g = "abc"
$DM946 = $g.length
$DM960 = $g
