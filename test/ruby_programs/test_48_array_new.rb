# Array.new / Hash.new
#
# 対象機種: KV-5000, KV-X500
#
# **`Array` は組み込みクラスとして登録します。** `OP_CLASS` に出てこない
# 大文字の名前は利用者の定数になるので、外さないと値スロットが未代入の
# まま `.new` を呼び、レシーバの型違いで止まります。型タグは
# `TT_BUILTIN_CLASS` (14) で、利用者のクラス (13) の隣です。
#
# **ブロック形は新しい反復です。** 渡すのは添字 (`times` と同じ) で、
# ブロックの値を要素へ書きます。`any?` で作った「ブロックの値を見る」
# 仕組みを使っていますが、**述語として扱われると 1 回目で打ち切られます**
# — i8080 で実際にそうなりました ($DM1204 がそこを見ます)。
#
# **容量は PLC が 12、i8080 が 8 要素です。** 定数で超えるとコンパイル時に
# 止まるので、ここには上限ちょうどまでしか書けません。
#
# 期待値:
#   $DM1200 = 3        大きさだけ。要素数
#   $DM1201 = 1        埋まっているのは nil (偽)
#   $DM1202 = 7        既定値で埋まる
#   $DM1203 = 3        既定値でも要素数は同じ
#   $DM1204 = 20       ブロックは添字を受け、値が要素になる (a[2])
#   $DM1205 = 3        ブロック形の要素数 (打ち切られていない)
#   $DM1206 = 0        空配列 (引数なし)
#   $DM1207 = 0        0 個のブロック形は 1 回も回らない
#   $DM1208 = 5        ブロックの break は値になる
#   $DM1209 = 0        Hash.new は空
#   $DM1210 = 9        Hash.new のあとは普通のハッシュ
#   $DM1211 = 12       上限ちょうど (PLC)
#
# 実機でのみ意味を持つ検証。

a = Array.new(3)
$DM1200 = a.length
$DM1201 = a[0] ? 0 : 1

b = Array.new(3, 7)
$DM1202 = b[2]
$DM1203 = b.length

c = Array.new(3) { |i| i * 10 }
$DM1204 = c[2]
$DM1205 = c.length

$DM1206 = Array.new.length

n = 0
d = Array.new(0) { n = 1 }
$DM1207 = n

$DM1208 = Array.new(3) { break 5 }

h = Hash.new
$DM1209 = h.length
h[1] = 9
$DM1210 = h[1]

e = Array.new(12, 1)
$DM1211 = e.length
