# 整数のビット演算
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# PLC はビットを立てたり落としたりする処理が多い。KV スクリプトの
# `AND` / `OR` / `XOR` / `NOT` はワードの演算子としてそのまま書ける。
# **条件式の連結には使えない**ので、そちらは今までどおり入れ子の `IF`。
# シフトは `SLA(元, 桁数, 先)` / `SRA(元, 桁数, 先)` の文。
#
# 32 ビット符号付きで計算する。整数だけで、実数を渡すと止まる。
#
# `<<` は整数なら左シフト、文字列と配列なら継ぎ足し (Ruby と同じ)。
#
# 期待値:
#   $D940 = 8       12 & 10
#   $D941 = 14      12 | 10
#   $D942 = 6       12 ^ 10
#   $D943 = -6      ~5
#   $D944 = 48      12 << 2
#   $D945 = 3       12 >> 2
#   $D946 = -3      -5 >> 1   切り下げ (Ruby と同じ)
#   $D947 = 1       ビットが立っているかを見る
#   $D948 = 0       落とした後
#   $D950L = 65536  1 << 16   32 ビットで計算する
#   $D952 = -10     -5 << 1   値が負でもよい
#   $D953 = 2       5 << -1   桁数が負なら逆向き (Ruby と同じ)
#   $D954 = 0       5 << 32   32 桁以上ずらすと左は 0
#   $D955 = -1      -5 >> 32  右は符号で埋まる
#
# 実機でのみ意味を持つ検証。

a = 12
b = 10
$D940 = a & b
$D941 = a | b
$D942 = a ^ b
$D943 = ~5
$D944 = a << 2
$D945 = a >> 2
$D946 = -5 >> 1

# ビットを立てて、見て、落とす
w = 0
w = w | 4
$D947 = 0
if (w & 4) != 0
  $D947 = 1
end
w = w & ~4
$D948 = 0
if (w & 4) != 0
  $D948 = 1
end

$D950L = 1 << 16

# 端の扱い。桁数が負なら向きが逆、32 桁以上は振り切る
$D952 = -5 << 1
$D953 = 5 << -1
$D954 = 5 << 32
$D955 = -5 >> 32
