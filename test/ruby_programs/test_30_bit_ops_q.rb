# 整数のビット演算
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# PLC はビットを立てたり落としたりする処理が多い。KV スクリプトの
# `AND` / `OR` / `XOR` / `NOT` はワードの演算子としてそのまま書ける。
# **条件式の連結には使えない**ので、そちらは今までどおり入れ子の `IF`。
# シフトは `SLA(元, 桁数, 先)` / `SRA(元, 桁数, 先)` の文。
#
# 32 ビット符号付きで計算する。整数だけで、実数を渡すと止まる。
#
# `<<` は整数なら左シフト、文字列と配列なら継ぎ足し (Ruby と同じ)。
#
# 期待値:
#   $D3940 = 8       12 & 10
#   $D3941 = 14      12 | 10
#   $D3942 = 6       12 ^ 10
#   $D3943 = -6      ~5
#   $D3944 = 48      12 << 2
#   $D3945 = 3       12 >> 2
#   $D3946 = -3      -5 >> 1   切り下げ (Ruby と同じ)
#   $D3947 = 1       ビットが立っているかを見る
#   $D3948 = 0       落とした後
#   $D3950L = 65536  1 << 16   32 ビットで計算する
#   $D3952 = -10     -5 << 1   値が負でもよい
#   $D3953 = 2       5 << -1   桁数が負なら逆向き (Ruby と同じ)
#   $D3954 = 0       5 << 32   32 桁以上ずらすと左は 0
#   $D3955 = -1      -5 >> 32  右は符号で埋まる
#
# 実機でのみ意味を持つ検証。

a = 12
b = 10
$D3940 = a & b
$D3941 = a | b
$D3942 = a ^ b
$D3943 = ~5
$D3944 = a << 2
$D3945 = a >> 2
$D3946 = -5 >> 1

# ビットを立てて、見て、落とす
w = 0
w = w | 4
$D3947 = 0
if (w & 4) != 0
  $D3947 = 1
end
w = w & ~4
$D3948 = 0
if (w & 4) != 0
  $D3948 = 1
end

$D3950L = 1 << 16

# 端の扱い。桁数が負なら向きが逆、32 桁以上は振り切る
$D3952 = -5 << 1
$D3953 = 5 << -1
$D3954 = 5 << 32
$D3955 = -5 >> 32
