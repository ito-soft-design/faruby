# 実数の確認
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# 期待値:
#   $D3520F = 3.0      実数の加算 2.5 + 0.5
#   $D3522F = 3.5      実数の除算 7.0 / 2.0 (切り下げない)
#   $D3524F = 5.5      整数と実数の混在 2.5 + 3
#   $D3526  = 3        実数をワードデバイスへ書くと0方向へ切り捨て
#   $D3528F = 2.0      整数をFデバイスへ書くと実数に変換される
#   $D3530  = 1        1 == 1.0 は真
#   $D3532  = 3        整数どうしの除算は切り下げのまま (7 / 2 = 3)
#
# 実機でのみ意味を持つ検証。

a = 2.5
b = 0.5
$D3520F = a + b

c = 7.0
d = 2.0
$D3522F = c / d

$D3524F = a + 3

# 実数をワードデバイス (16bit符号付き) へ書くと切り捨てられる
$D3526 = 3.7

# 整数を F デバイスへ書くと実数に変換される
$D3528F = 2

if 1 == 1.0
  $D3530 = 1
else
  $D3530 = 0
end

e = 7
f = 2
$D3532 = e / f
