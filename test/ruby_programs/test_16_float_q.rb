# 実数の確認
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# 期待値:
#   $D520F = 3.0      実数の加算 2.5 + 0.5
#   $D522F = 3.5      実数の除算 7.0 / 2.0 (切り下げない)
#   $D524F = 5.5      整数と実数の混在 2.5 + 3
#   $D526  = 3        実数をワードデバイスへ書くと0方向へ切り捨て
#   $D528F = 2.0      整数をFデバイスへ書くと実数に変換される
#   $D530  = 1        1 == 1.0 は真
#   $D532  = 3        整数どうしの除算は切り下げのまま (7 / 2 = 3)
#
# 実機でのみ意味を持つ検証。

a = 2.5
b = 0.5
$D520F = a + b

c = 7.0
d = 2.0
$D522F = c / d

$D524F = a + 3

# 実数をワードデバイス (16bit符号付き) へ書くと切り捨てられる
$D526 = 3.7

# 整数を F デバイスへ書くと実数に変換される
$D528F = 2

if 1 == 1.0
  $D530 = 1
else
  $D530 = 0
end

e = 7
f = 2
$D532 = e / f
