# test_40_device_map_melsec.rb の割り付け表 (三菱)
#
# **キーエンス版から割り付け先だけを置き換えたものです** (`MR` → `M`、
# `DM` → `D`)。プログラムの側は 1 文字も変わりません。**それがこの仕組みの
# 値打ちです。**

FaRuby.devices do
  map "motor", "M101"      # ビットデバイス
  map "count", "D1040"     # ワードデバイス
  map "speed", "D1041L"    # 割り付け先に幅が付いている (D1041 と D1042)

  # **連番の配線は繰り返しで書ける。** これが Ruby にした値打ち
  4.times { |i| map "in_#{i}", "D#{1045 + i}" }
end
