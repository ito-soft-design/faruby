# 文字列の比較と連結
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# **`==` は中身で比べる。** レジスタに入っているのはスロット番号なので、
# 同じ内容が別のスロットにあると番号では等しくならない。バイト数が同じなら
# ワード単位で比べる (並びが揃っているので回数はバイト数の半分)。
#
# ハッシュの鍵も同じ判定にする。文字列の鍵はスロットが違っても同じ鍵。
#
# 連結は 2 つ。`+` は新しいスロットを取り、`OP_STRCAT` (式展開) は
# 継ぎ足す先をそのまま伸ばす。継ぎ足す先の長さが奇数だとワードの途中から
# 始まるので、そこはバイト単位で書く。
#
# 期待値:
#   $D960 = 1       別のスロットの同じ内容は等しい
#   $D961 = 1       長さが違えば等しくない
#   $D962 = 7       文字列の鍵で引ける
#   $D963 = 9       新しい文字列の鍵を足せる
#   $D970U = 24930  "ab"   a + b
#   $D971U = 25444  "cd"
#   $D972U = 0      終端
#   $D974U = 28792  "px"   式展開 "p#{c}q"
#   $D975U = 28928  "q\0"
#   $D978U = 24930  "ab"   + は左側を変えない
#   $D979U = 0      終端
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと `+` の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

FARUBY_STR_FILL = 0x20

s = "hello"
t = "hello"

$D960 = 0
if s == t
  $D960 = 1
end

$D961 = 0
if s != "hell"
  $D961 = 1
end

# 文字列の鍵。書いたときと引くときで別のスロットになる
h = { "x" => 7 }
$D962 = h["x"]
h["z"] = 9
$D963 = h["z"]

a = "ab"
b = "cd"
$D970 = a + b

c = "x"
$D974 = "p#{c}q"

# + は新しいスロットを取るので、左側は変わらない
$D978 = a
