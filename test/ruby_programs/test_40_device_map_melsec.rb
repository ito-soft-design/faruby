# 期待値:
#   $motor = 1        割り付けたビットデバイス (M101)
#   $count = 7        割り付けたワードデバイス (D1040)
#   $speed = 100000   割り付け先に幅が付いている (D1041L の 2 ワード)
#   $D1043 = 6        繰り返しで生成した割り付け (in_0..in_3 の和)
#   $D1044 = 42       割り付けた名前と実デバイスは混ぜて書ける
#
# 実機でのみ意味を持つ検証。

