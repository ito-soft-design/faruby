# 文字列のメソッド
#
# 対象機種: Q, iQ-R
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# **`length` は文字数を返す。** `"あ".length` は Ruby では 1 で、バイト数の
# 3 ではない。バイト列を先頭から 1 回なめて切れ目を数える。同じ走査で
# `s[i]` のバイト位置も出るので、両方を同じ手順で済ませている。
#
# `empty?` は長さが 0 かどうかだけなので、切れ目は数えない。
#
# `<<` は文字列なら中身を継ぎ足し、配列なら末尾に足す。どちらも Ruby は
# レシーバ自身を返す。`push` は配列だけ (Ruby の String に push は無い)。
#
# `s[i]` は **1 文字の文字列**を返す。プールを 1 スロット使うので、
# ループの中で呼び続けると使い切る。
#
# 期待値:
#   $D940 = 5       "hello".length
#   $D941 = 5       size も同じ
#   $D942 = 2       "あい".length は文字数。バイト数の 6 ではない
#   $D944 = 1       "".empty?
#   $D945 = 0       "a".empty? は偽
#   $D946 = 1       [].empty?
#   $D947 = 0       { 1 => 2 }.empty? は偽
#   $D948 = 4       文字列の << で伸びた長さ
#   $D949 = 3       配列の << は今までどおり
#   $D960U = 24832  s[0] は "a"。終端付きなので下位バイトは 0
#   $D962U = 25600  s[-1] は "d"。負の添字は後ろから数える
#   $D964U = 0      s[9] は範囲外で nil
#   $D966U = 58241  "あい"[1] は 3 バイトの "い"
#   $D967U = 33792
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと s[i] の結果がそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

h = "hello"
$D940 = h.length
$D941 = h.size

j = "あい"
$D942 = j.length

$D944 = 0
if "".empty?
  $D944 = 1
end

$D945 = 0
if "a".empty?
  $D945 = 1
end

$D946 = 0
if [].empty?
  $D946 = 1
end

k = { 1 => 2 }
$D947 = 0
if k.empty?
  $D947 = 1
end

s = "abc"
s << "d"
$D948 = s.length

a = [1, 2]
a << 3
$D949 = a.length

$D960 = s[0]
$D962 = s[-1]
$D964 = s[9]
$D966 = j[1]
