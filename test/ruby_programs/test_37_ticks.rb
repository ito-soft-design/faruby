# 経過時間とクロックパルス
#
# 対象機種: KV-5000, KV-X500
#
# `$FARUBY_TICKS` は電源投入からのミリ秒です。生成スクリプトが 10ms クロック
# (CR2004) の立ち上がりをスキャンごとに数えて進めます。**実機でしか意味を
# 持ちません。** シミュレータには 1 スキャンにあたるものが無いためです。
#
# `$FARUBY_CLOCK_10MS` / `_100MS` / `_1S` はパルスそのもので、**真偽値**で
# 返ります。値スロットにタグごと写しているためで、1 / 0 の整数だと Ruby では
# 0 も真になり `if` に使えません。
#
# **時間を待つ書き方は差分です。** VM はスキャンごとに戻るので、止まって
# 待つ `sleep` は作れません。回数ではなく**経った時間で**回します。回数だと
# スキャンの速さで待つ長さが変わり、機種によってパルスの山をまたげません。
#
# 300ms 回すので、100ms クロックは 3 周ぶん入れ替わります。
#
# 期待値:
#   $DM1010 = 1      経った時間が 0 より大きい (ticks が進んでいる)
#   $DM1011 = 1      100ms クロックが真になったところを見た
#   $DM1012 = 1      100ms クロックが偽になったところを見た
#   $DM1013 = 1      1s クロックが真偽のどちらかで読めた
#   $DM1014 = 1      経った時間が 10 の倍数 (10ms ずつ足している)
#
# 調べる用に、期待値を置かないものも書きます。
#
#   $DM1015          実際に経った時間 (ミリ秒)
#   $DM1016L         回った回数
#
# 実機でのみ意味を持つ検証。**KV-5000 と KV-X500 で 5 値一致** (CR2004 が
# 10ms、CR2005 が 100ms であることの裏付けでもあります)。

t0 = $FARUBY_TICKS

seen_on = false
seen_off = false
i = 0
elapsed = 0
while elapsed < 300
  i = i + 1
  if $FARUBY_CLOCK_100MS
    seen_on = true
  else
    seen_off = true
  end
  elapsed = $FARUBY_TICKS - t0
  # ticks が進まないときの逃げ道。**止まったまま戻らなくなるのを防ぐ**
  elapsed = 300 if i > 200000
end

$DM1015 = elapsed
$DM1016L = i

$DM1010 = 0
$DM1011 = 0
$DM1012 = 0
$DM1013 = 0
$DM1014 = 0

$DM1010 = 1 if elapsed > 0
$DM1011 = 1 if seen_on
$DM1012 = 1 if seen_off
$DM1013 = 1 if $FARUBY_CLOCK_1S
$DM1013 = 1 unless $FARUBY_CLOCK_1S
$DM1014 = 1 if elapsed % 10 == 0
