# 汎用グローバル変数はどの型でも持てる
#
# 対象機種: Q
#
# **キーエンス版から機種名だけを置き換えたものです** (`DM` → `D`、`MR` → `M`)。
# アドレスはそのままで、faRuby の D4000-D5999 とも GX Works2 が一時変数に使う
# D6144 以降とも重なりません。
#
# `$foo` のようにデバイス名でないグローバル変数は、汎用グローバル領域の
# **値スロット (4 ワード)** に置く。型タグごと写すので、実数も配列も
# ハッシュも文字列も `true` / `false` / `nil` もそのまま持てる。
#
# 以前は値ワードだけを 32 ビットで読み書きしていたため、実数は切り捨てられ、
# `false` と `nil` は整数 0 になって**真**になっていた。配列や文字列は
# スロット番号が整数として残り、使うとエラーで止まった。
#
# 配列や文字列を入れてもプールは増えない。入るのはスロット番号だけ。
#
# 期待値:
#   $D940 = 1       実数がそのまま
#   $D941 = 3       配列の length が引ける
#   $D942 = 2       ハッシュが引ける
#   $D943 = 0       false は偽
#   $D944 = 0       nil は偽
#   $D945 = 1       true は真
#   $D946 = 3       文字列の length が引ける
#   $D960U = 24930  文字列をデバイスへ書ける "ab"
#   $D961U = 25344  "c" と終端
#
# 実機でのみ意味を持つ検証。

$g = 2.5
$D940 = 0
if $g == 2.5
  $D940 = 1
end

$g = [1, 2, 3]
$D941 = $g.length

$g = { 1 => 2 }
$D942 = $g[1]

$g = false
$D943 = 0
if $g
  $D943 = 1
end

$g = nil
$D944 = 0
if $g
  $D944 = 1
end

$g = true
$D945 = 0
if $g
  $D945 = 1
end

$g = "abc"
$D946 = $g.length
$D960 = $g
