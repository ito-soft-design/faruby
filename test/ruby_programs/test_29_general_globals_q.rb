# 汎用グローバル変数はどの型でも持てる
#
# 対象機種: Q
#
# **出力先は D3000 台**です。faRuby 自身が D4000-D5999、GX Works2 の自動割付が
# D6144 以降を使うので、そこから離しています。
#
# `$foo` のようにデバイス名でないグローバル変数は、汎用グローバル領域の
# **値スロット (4 ワード)** に置く。型タグごと写すので、実数も配列も
# ハッシュも文字列も `true` / `false` / `nil` もそのまま持てる。
#
# 以前は値ワードだけを 32 ビットで読み書きしていたため、実数は切り捨てられ、
# `false` と `nil` は整数 0 になって**真**になっていた。配列や文字列は
# スロット番号が整数として残り、使うとエラーで止まった。
#
# 配列や文字列を入れてもプールは増えない。入るのはスロット番号だけ。
#
# 期待値:
#   $D3940 = 1       実数がそのまま
#   $D3941 = 3       配列の length が引ける
#   $D3942 = 2       ハッシュが引ける
#   $D3943 = 0       false は偽
#   $D3944 = 0       nil は偽
#   $D3945 = 1       true は真
#   $D3946 = 3       文字列の length が引ける
#   $D3960U = 24930  文字列をデバイスへ書ける "ab"
#   $D3961U = 25344  "c" と終端
#
# 実機でのみ意味を持つ検証。

$g = 2.5
$D3940 = 0
if $g == 2.5
  $D3940 = 1
end

$g = [1, 2, 3]
$D3941 = $g.length

$g = { 1 => 2 }
$D3942 = $g[1]

$g = false
$D3943 = 0
if $g
  $D3943 = 1
end

$g = nil
$D3944 = 0
if $g
  $D3944 = 1
end

$g = true
$D3945 = 0
if $g
  $D3945 = 1
end

$g = "abc"
$D3946 = $g.length
$D3960 = $g
