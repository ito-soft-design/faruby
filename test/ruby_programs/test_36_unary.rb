# 単項の符号と括弧
#
# 対象機種: KV-5000, KV-X500
#
# **mruby は `-x` を `x.-@()` にします。** リテラルは定数畳み込みで消えるので、
# `-1` は届きません。変数や式に付けたときだけメソッド呼び出しになります。
# `+x` も同じく `+@` になり、Ruby と同じく何もしません。
#
# 括弧そのものは faRuby に届きません。mruby が順序を決めてバイトコードに
# するので、ここで見ているのは**順序が正しく実行されるか**です。
#
# 期待値:
#   $DM990 = 14      a + b * c        掛け算が先
#   $DM991 = 20      (a + b) * c      括弧が先
#   $DM992 = 13      a * (b + c) - 1
#   $DM993 = 5       ((a+b) * (c-1)) / 3
#   $DM994 = 1       -(a - b)         式に付けた単項マイナス
#   $DM995 = -2      -a               変数に付けた単項マイナス
#   $DM996 = 2       +a               単項プラスは何もしない
#   $DM997 = -1      -x.abs           メソッドの結果に付ける
#   $DM1000L = -25   -(5 * 5)         32ビット (DM1000-DM1001)
#   $DM1002F = -2.5  -y               実数 (DM1002-DM1003)
#
# **幅のあるものは離して置きます。** `$DM998L` と `$DM999F` は 1 ワード
# 重なり、後に書いた方が相手の上位ワードを潰します。
#
# 実機でのみ意味を持つ検証。

a = 2
b = 3
c = 4

$DM990 = a + b * c
$DM991 = (a + b) * c
$DM992 = a * (b + c) - 1
$DM993 = ((a + b) * (c - 1)) / 3

$DM994 = -(a - b)
$DM995 = -a
$DM996 = +a

x = -1
$DM997 = -x.abs
$DM1000L = -(5 * 5)

y = 2.5
$DM1002F = -y
