# デバイスから文字列を読む
#
# **桁数がそのままバイト数。何も落とさない。** 表示器の桁が空白で埋まって
# いれば、その空白も中身に入る。落とす規則を持つと、末尾の空白が意味を持つ
# データを扱えなくなる。比べたい桁に合わせて書く。
#
# 桁の無い `T` は読めない。書くときは終端付きの意味だが、読むときは
# 長さが決まらないため。エラー 21。
#
# 添字を付けた形 (`$DMT6[i]`) も同じ経路を通る。表示器の桁が並んでいる
# ところから 1 つずつ読める。
#
# 期待値:
#   $DM940 = 6       読み戻した長さ
#   $DM941 = 1       同じ中身なら等しい
#   $DM942 = 3       奇数の桁も読める
#   $DM943 = 1       桁の外のバイトは混ざらない
#   $DM944 = 2       "あい" は 6 バイトで 2 文字
#   $DM945 = 1       添字を付けた形も読める
#   $DM960U = 16706  読んだものを書き戻すと同じ並び
#   $DM961U = 17220
#   $DM962U = 17734
#   $DM963U = 0
#
# 実機でのみ意味を持つ検証。
#
# 文字列リテラルと読み取りがそれぞれプールを 1 スロット使う。
# 16 スロットしかないので、行を増やすときは残りに気をつけること。

$DM100T6 = "ABCDEF"
s = $DM100T6
$DM940 = s.length

$DM941 = 0
if s == "ABCDEF"
  $DM941 = 1
end

# 奇数の桁。最後のワードの下位バイトは桁の外
$DM110T3 = "xyz"
t = $DM110T3
$DM942 = t.length
$DM943 = 0
if t == "xyz"
  $DM943 = 1
end

# UTF-8 は 1 文字 3 バイト。桁はバイト数で数える
$DM120T6 = "あい"
u = $DM120T6
$DM944 = u.length

# 添字を付けた形。桁は名前側に付ける ($DMT6)
i = 0
v = $DMT6[100 + i]
$DM945 = 0
if v == "ABCDEF"
  $DM945 = 1
end

$DM960 = s
